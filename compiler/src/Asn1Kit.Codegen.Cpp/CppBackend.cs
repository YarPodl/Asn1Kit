using System.Text;
using Asn1Kit.Codegen;
using Asn1Kit.Ir;

namespace Asn1Kit.Codegen.Cpp;

public sealed partial class CppBackend : ILanguageBackend
{
    public string LanguageId => "cpp";

    public IReadOnlyList<GeneratedFile> Generate(IrDocument document)
    {
        OpenTypeBindings.NormalizeLegacy(document);
        return document.Modules
            .Where(module => module.Types.Any(static type => IrOptions.ShouldGenerate(type.Options)))
            .Select(module => GenerateModule(document, module))
            .ToList();
    }

    private GeneratedFile GenerateModule(IrDocument document, IrModule module)
    {
        ResetOpenTypeState();
        var ns = ModuleNamespace(module);
        var builder = new StringBuilder();
        var guard = CppNames.IncludeGuard(module.Name);
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine($"#ifndef {guard}");
        builder.AppendLine($"#define {guard}");
        builder.AppendLine();
        builder.AppendLine("#include \"asn1kit/any.hpp\"");
        builder.AppendLine("#include \"asn1kit/bit_string.hpp\"");
        builder.AppendLine("#include \"asn1kit/bytes.hpp\"");
        builder.AppendLine("#include \"asn1kit/codec.hpp\"");
        builder.AppendLine("#include \"asn1kit/contained.hpp\"");
        builder.AppendLine("#include \"asn1kit/exception.hpp\"");
        builder.AppendLine("#include \"asn1kit/integer.hpp\"");
        builder.AppendLine("#include \"asn1kit/lazy.hpp\"");
        builder.AppendLine("#include \"asn1kit/null.hpp\"");
        builder.AppendLine("#include \"asn1kit/oid.hpp\"");
        builder.AppendLine("#include \"asn1kit/reader.hpp\"");
        builder.AppendLine("#include \"asn1kit/tag.hpp\"");
        builder.AppendLine("#include \"asn1kit/utc_date_time.hpp\"");
        builder.AppendLine("#include \"asn1kit/value.hpp\"");
        builder.AppendLine("#include \"asn1kit/writer.hpp\"");
        builder.AppendLine();
        builder.AppendLine("#include <cstdint>");
        builder.AppendLine("#include <optional>");
        builder.AppendLine("#include <string>");
        builder.AppendLine("#include <utility>");
        builder.AppendLine("#include <variant>");
        builder.AppendLine("#include <vector>");
        builder.AppendLine();
        builder.Append(CppNames.NamespaceOpen(ns));
        builder.AppendLine();

        var queue = new Queue<(string Name, TypeExpr Type)>();
        foreach (var type in module.Types)
        {
            if (!IrOptions.ShouldGenerate(type.Options))
            {
                continue;
            }

            RejectUnsupportedOptions(type.Options, type.Type);
            EnsureBackendSupport(document, module, type.Type);

            if (IrOptions.CppAliasOf(type.Options) is not null)
            {
                continue;
            }

            var typeName = IrOptions.CppTypeName(type.Options) ?? CppNames.SanitizeTypeName(type.Name);
            if (IsCollapsibleAlias(type.Type))
            {
                CollectNested(document, module, typeName, type.Type, queue);
                continue;
            }

            queue.Enqueue((typeName, type.Type));
        }

        var emitted = new HashSet<string>(StringComparer.Ordinal);
        var nested = new List<(string Name, TypeExpr Type)>();
        while (queue.Count > 0)
        {
            var (name, type) = queue.Dequeue();
            if (!emitted.Add(name))
            {
                continue;
            }

            CollectNested(document, module, name, type, queue);
            nested.Add((name, type));
        }

        var openPlan = PlanDirectOpenTypes(document, module, nested, emitted);
        CollectOpenTypeNested(document, module, openPlan, queue);
        while (queue.Count > 0)
        {
            var (name, type) = queue.Dequeue();
            if (!emitted.Add(name))
            {
                continue;
            }

            CollectNested(document, module, name, type, queue);
            nested.Add((name, type));
        }

        var oidValues = CollectOidValues(module);
        if (oidValues.Count > 0)
        {
            var catalogName = OidCatalogName(module);
            if (emitted.Contains(catalogName))
            {
                throw new NotSupportedException(
                    $"Generated OID catalog '{catalogName}' in module '{module.Name}' conflicts with a generated type.");
            }

            EmitOidCatalog(builder, catalogName, oidValues);
            builder.AppendLine();
        }

        foreach (var (name, type) in nested)
        {
            EmitType(builder, document, module, name, type);
            builder.AppendLine();
        }

        EmitOpenTypes(builder, document, module, openPlan);

        builder.Append(CppNames.NamespaceClose(ns));
        builder.AppendLine($"#endif // {guard}");

        return new GeneratedFile(CppNames.SanitizeTypeName(module.Name) + ".hpp", builder.ToString());
    }

    private static string ModuleNamespace(IrModule module) =>
        IrOptions.CppNamespace(module.Options) ?? CppNames.SanitizeTypeName(module.Name);

    private static string OidCatalogName(IrModule module) =>
        CppNames.SanitizeTypeName(module.Name) + "Oids";

    private static List<(string Name, string Dotted)> CollectOidValues(IrModule module)
    {
        var result = new List<(string Name, string Dotted)>();
        foreach (var definition in module.Values)
        {
            if (!IrOptions.ShouldGenerate(definition.Options))
            {
                continue;
            }

            if (definition.Value is IrOidValue oid)
            {
                result.Add((CppNames.SanitizeTypeName(definition.Name), oid.Value));
            }
        }

        return result;
    }

    private static void EmitOidCatalog(
        StringBuilder sb,
        string catalogName,
        IReadOnlyList<(string Name, string Dotted)> values)
    {
        sb.AppendLine($"struct {catalogName} {{");
        foreach (var (name, dotted) in values)
        {
            sb.AppendLine(
                $"    static constexpr const char* {name} = \"{CppNames.EscapeString(dotted)}\";");
        }

        sb.AppendLine();
        foreach (var (name, _) in values)
        {
            sb.AppendLine($"    static asn1kit::oid {name}_oid() {{");
            sb.AppendLine($"        return asn1kit::oid::parse({name});");
            sb.AppendLine("    }");
        }

        sb.AppendLine("};");
    }

    private void CollectNested(
        IrDocument document,
        IrModule module,
        string owner,
        TypeExpr type,
        Queue<(string Name, TypeExpr Type)> queue)
    {
        switch (type)
        {
            case OctetStringType { Containing: { } content }:
                OfferNested(document, module, owner + "_Content", content, queue);
                break;
            case BitStringType { Containing: { } bitContent }:
                OfferNested(document, module, owner + "_Content", bitContent, queue);
                break;
            case SequenceType sequence:
                foreach (var component in sequence.Components)
                {
                    OfferNested(
                        document,
                        module,
                        owner + "_" + CppNames.SanitizeTypeName(component.Name),
                        component.Type,
                        queue);
                }

                break;
            case SetType set:
                foreach (var component in set.Components)
                {
                    OfferNested(
                        document,
                        module,
                        owner + "_" + CppNames.SanitizeTypeName(component.Name),
                        component.Type,
                        queue);
                }

                break;
            case ChoiceType choice:
                if (IsSingleAlternativeChoice(choice))
                {
                    OfferNested(document, module, owner, choice.Components[0].Type, queue);
                }
                else
                {
                    foreach (var component in choice.Components)
                    {
                        OfferNested(
                            document,
                            module,
                            owner + "_" + CppNames.SanitizeTypeName(component.Name),
                            component.Type,
                            queue);
                    }
                }

                break;
            case SequenceOfType sequenceOf:
                OfferNested(document, module, owner + "_Item", sequenceOf.Element, queue);
                break;
            case SetOfType setOf:
                OfferNested(document, module, owner + "_Item", setOf.Element, queue);
                break;
        }
    }

    private void OfferNested(
        IrDocument document,
        IrModule module,
        string hint,
        TypeExpr type,
        Queue<(string Name, TypeExpr Type)> queue)
    {
        if (NeedsNamedType(type) || IsEnumerated(type) || IsNamedInteger(type) || IsNamedBitString(type))
        {
            queue.Enqueue((hint, type));
            if (NeedsNamedType(type))
            {
                CollectNested(document, module, hint, type, queue);
            }
        }
        else if (type is RefType)
        {
            return;
        }
        else if (ContainedType(type) is { } content)
        {
            OfferNested(document, module, hint + "_Content", content, queue);
        }
        else if (type is SequenceOfType or SetOfType or SequenceType or SetType or ChoiceType)
        {
            CollectNested(document, module, hint, type, queue);
        }
    }

    private void EmitType(StringBuilder sb, IrDocument document, IrModule module, string typeName, TypeExpr type)
    {
        EnsureBackendSupport(document, module, type);
        switch (type)
        {
            case SequenceType sequence:
                EmitSequence(sb, document, module, typeName, sequence);
                break;
            case SetType set:
                EmitSet(sb, document, module, typeName, set);
                break;
            case ChoiceType choice:
                EmitChoice(sb, document, module, typeName, choice);
                break;
            case BitStringType bitString when IsNamedBitString(bitString):
                EmitNamedBitString(sb, typeName, bitString);
                break;
            case EnumeratedType enumerated:
                EmitEnumerated(sb, typeName, enumerated);
                break;
            case IntegerType integer when IsNamedInteger(integer):
                EmitNamedIntegerConstants(sb, typeName, integer);
                break;
            case SequenceOfType:
            case SetOfType:
                throw new NotSupportedException(
                    $"C++ backend does not emit a named type for '{type.Kind}'; use std::vector via field encode/decode.");
            default:
                throw new InvalidOperationException(
                    $"C++ backend refused to emit collapsible alias '{typeName}' (kind '{type.Kind}').");
        }
    }
}
