using System.Globalization;
using System.Text;
using Asn1Kit.Ir;

namespace Asn1Kit.Codegen.Cpp;

public sealed partial class CppBackend
{
    /// <summary>
    /// True when a named generated type gets its own <c>to_string</c> overload.
    /// Named INTEGER constant structs carry no state and are skipped.
    /// </summary>
    private static bool HasFormatDefinition(TypeExpr type) =>
        type is SequenceType or SetType or ChoiceType or EnumeratedType
        || (type is BitStringType bit && IsNamedBitString(bit));

    private GeneratedFile EmitFormatFile(
        IrDocument document,
        ModulePlan plan,
        IReadOnlyList<(IrModule Module, string Name, TypeExpr Type)> items,
        Dictionary<(string Module, string Name), int> keyOf)
    {
        var module = plan.Module;
        var ns = ModuleNamespace(module);
        var own = plan.Nested.Where(t => HasFormatDefinition(t.Type)).ToList();

        var builder = new StringBuilder();
        var guard = CppNames.IncludeGuard(module.Name + "_format");
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("// Deep debug formatting: forward declarations, peer includes, inline definitions.");
        builder.AppendLine($"#ifndef {guard}");
        builder.AppendLine($"#define {guard}");
        builder.AppendLine();
        builder.AppendLine($"#include \"{CppNames.SanitizeTypeName(module.Name)}.hpp\"");
        builder.AppendLine("#include \"asn1kit/format.hpp\"");
        builder.AppendLine();

        // Declarations must precede peer includes so a mutual (cycle) pair can see
        // each other's to_string through the include guards.
        builder.Append(CppNames.NamespaceOpen(ns));
        builder.AppendLine();
        foreach (var (name, _) in own)
        {
            builder.AppendLine($"inline void to_string(const {name}& value, std::ostream& out, int indent);");
        }

        builder.Append(CppNames.NamespaceClose(ns));
        builder.AppendLine();

        var peers = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var (name, type) in own)
        {
            var deps = new HashSet<int>();
            CollectNamedTypeDeps(document, module, type, name, keyOf, deps);
            foreach (var index in deps)
            {
                var dep = items[index];
                if (!HasFormatDefinition(dep.Type))
                {
                    continue;
                }

                if (string.Equals(dep.Module.Name, module.Name, StringComparison.Ordinal))
                {
                    continue;
                }

                peers.Add(CppNames.SanitizeTypeName(dep.Module.Name) + ".format.hpp");
            }
        }

        foreach (var include in peers)
        {
            builder.AppendLine($"#include \"{include}\"");
        }

        if (peers.Count > 0)
        {
            builder.AppendLine();
        }

        builder.Append(CppNames.NamespaceOpen(ns));
        builder.AppendLine();
        builder.AppendLine("using asn1kit::to_string;");
        builder.AppendLine();
        foreach (var (name, type) in own)
        {
            EmitFormatDefinition(builder, document, module, name, type);
            builder.AppendLine();
        }

        builder.Append(CppNames.NamespaceClose(ns));
        builder.AppendLine();
        builder.AppendLine($"#endif // {guard}");
        return new GeneratedFile(CppNames.SanitizeTypeName(module.Name) + ".format.hpp", builder.ToString());
    }

    private void EmitFormatDefinition(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string typeName,
        TypeExpr type)
    {
        switch (type)
        {
            case SequenceType sequence:
                EmitStructuredFormatDefinition(sb, typeName, sequence.Components);
                break;
            case SetType set:
                EmitStructuredFormatDefinition(sb, typeName, set.Components);
                break;
            case ChoiceType choice:
                EmitChoiceFormatDefinition(sb, document, module, typeName, choice);
                break;
            case EnumeratedType enumerated:
                EmitEnumeratedFormatDefinition(sb, typeName, enumerated);
                break;
            case BitStringType bit when IsNamedBitString(bit):
                EmitNamedBitStringFormatDefinition(sb, typeName);
                break;
        }
    }

    private static void EmitStructuredFormatDefinition(
        StringBuilder sb,
        string typeName,
        IReadOnlyList<IrComponent> components)
    {
        var name = CppNames.EscapeString(typeName);
        sb.AppendLine($"inline void to_string(const {typeName}& value, std::ostream& out, int indent) {{");
        if (components.Count == 0)
        {
            sb.AppendLine("    (void)value;");
        }

        sb.AppendLine($"    out << \"{name} {{\";");
        sb.AppendLine("    const auto pad = std::string(static_cast<std::size_t>(indent + 1) * 4, ' ');");
        if (components.Count == 0)
        {
            sb.AppendLine("    (void)pad;");
        }

        foreach (var field in components)
        {
            sb.AppendLine("    out << '\\n' << pad;");
            sb.AppendLine($"    out << \"{CppNames.EscapeString(field.Name)}: \";");
            sb.AppendLine($"    to_string(value.{FieldName(field)}, out, indent + 1);");
        }

        sb.AppendLine("    out << '\\n' << std::string(static_cast<std::size_t>(indent) * 4, ' ') << '}';");
        sb.AppendLine("}");
    }

    private void EmitChoiceFormatDefinition(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string typeName,
        ChoiceType type)
    {
        var alts = type.Components;
        var kinds = alts.Select(a => CppNames.SanitizeEnumMember(a.Name)).ToList();
        var payloadTypes = alts
            .Select(a => CppType(document, module, typeName, a.Name, a.Type, optional: false))
            .ToList();
        var variantTypes = payloadTypes.Distinct(StringComparer.Ordinal).ToList();
        var variantIndices = payloadTypes.Select(t => variantTypes.IndexOf(t)).ToList();
        var singlePayload = variantTypes.Count == 1;
        var name = CppNames.EscapeString(typeName);

        sb.AppendLine($"inline void to_string(const {typeName}& value, std::ostream& out, int indent) {{");
        if (alts.Count == 0 && !type.Extensible)
        {
            sb.AppendLine("    (void)value;");
            sb.AppendLine("    (void)out;");
            sb.AppendLine("    (void)indent;");
            sb.AppendLine("}");
            return;
        }

        sb.AppendLine("    switch (value.kind) {");

        void EmitCase(string kind, string label, string payload)
        {
            sb.AppendLine($"    case {typeName}_kind::{kind}:");
            sb.AppendLine("        {");
            sb.AppendLine($"            out << \"{CppNames.EscapeString(typeName)} {{\";");
            sb.AppendLine(
                "            out << '\\n' << std::string(static_cast<std::size_t>(indent + 1) * 4, ' ');");
            sb.AppendLine($"            out << \"kind: {CppNames.EscapeString(label)}\";");
            sb.AppendLine(
                "            out << '\\n' << std::string(static_cast<std::size_t>(indent + 1) * 4, ' ');");
            sb.AppendLine("            out << \"value: \";");
            sb.AppendLine($"            to_string({payload}, out, indent + 1);");
            sb.AppendLine(
                "            out << '\\n' << std::string(static_cast<std::size_t>(indent) * 4, ' ') << '}';");
            sb.AppendLine("            break;");
            sb.AppendLine("        }");
        }

        for (var i = 0; i < alts.Count; i++)
        {
            var payload = singlePayload
                ? "value.value"
                : $"std::get<{variantIndices[i].ToString(CultureInfo.InvariantCulture)}>(value.value)";
            EmitCase(kinds[i], alts[i].Name, payload);
        }

        if (type.Extensible)
        {
            EmitCase("unknown", "unknown", "value.unknown");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    private static void EmitEnumeratedFormatDefinition(
        StringBuilder sb,
        string typeName,
        EnumeratedType type)
    {
        var useLong = type.Values.Any(v => v.Value is < int.MinValue or > int.MaxValue);
        var underlying = useLong ? "std::int64_t" : "std::int32_t";
        sb.AppendLine($"inline void to_string(const {typeName}& value, std::ostream& out, int indent) {{");
        sb.AppendLine("    (void)indent;");
        sb.AppendLine("    switch (value) {");
        foreach (var value in type.Values)
        {
            sb.AppendLine(
                $"    case {typeName}::{CppNames.SanitizeEnumMember(value.Name)}:");
            sb.AppendLine($"        out << \"{CppNames.EscapeString(value.Name)}\";");
            sb.AppendLine("        break;");
        }

        sb.AppendLine("    default:");
        sb.AppendLine($"        out << static_cast<{underlying}>(value);");
        sb.AppendLine("        break;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    private static void EmitNamedBitStringFormatDefinition(StringBuilder sb, string typeName)
    {
        sb.AppendLine($"inline void to_string(const {typeName}& value, std::ostream& out, int indent) {{");
        sb.AppendLine($"    out << \"{CppNames.EscapeString(typeName)} {{ \";");
        sb.AppendLine("    to_string(value.value, out, indent);");
        sb.AppendLine("    out << \" }\";");
        sb.AppendLine("}");
    }
}
