    private string? ResolvePrimitive(TypeExpr type) => type switch
    {
        BooleanType => TypeKinds.Boolean,
        IntegerType => TypeKinds.Integer,
        BitStringType => TypeKinds.BitString,
        OctetStringType => TypeKinds.OctetString,
        NullType => TypeKinds.Null,
        OidType => TypeKinds.Oid,
        StringType => TypeKinds.String,
        TimeType => TypeKinds.Time,
        AnyType => TypeKinds.Any,
        _ => null
    };

    /// <summary>
    /// Collapse typedef aliases and single-alternative CHOICE to the underlying type used in generated C#.
    /// Stops at multi-alternative CHOICE / SEQUENCE / SET, named BIT STRING, and ENUMERATED (those keep a type).
    /// </summary>
    private TypeExpr UnwrapAliases(IrDocument document, IrModule module, TypeExpr type)
    {
        var visited = new HashSet<string>(StringComparer.Ordinal);
        while (true)
        {
            if (type is RefType reference)
            {
                var key = (reference.Module ?? module.Name) + "::" + reference.Name;
                if (!visited.Add(key))
                {
                    throw new NotSupportedException($"Circular type alias '{reference.Name}'.");
                }

                var found = FindWithModule(document, module, reference);
                if (found is null)
                {
                    return type;
                }

                var inner = found.Value.Def.Type;
                if (IsNamedBitString(inner) || NeedsNamedType(inner) || IsEnumerated(inner))
                {
                    return type;
                }

                var next = CloneType(inner);
                if (type.Tag is not null && next.Tag is null)
                {
                    next.Tag = type.Tag;
                }

                next.Options = MergeIntegerRepresentationOptions(
                    next.Options,
                    type.Options,
                    found.Value.Def.Options);

                type = next;
                continue;
            }

            if (IsSingleAlternativeChoice(type))
            {
                var choice = (ChoiceType)type;
                var next = CloneType(choice.Components[0].Type);
                if (type.Tag is not null && next.Tag is null)
                {
                    next.Tag = type.Tag;
                }

                type = next;
                continue;
            }

            return type;
        }
    }

    private static JsonObject? MergeIntegerRepresentationOptions(
        JsonObject? target,
        JsonObject? first,
        JsonObject? second)
    {
        if (IrOptions.IntegerRepresentation(target) is not null)
        {
            return target;
        }

        var representation = IrOptions.IntegerRepresentation(first)
            ?? IrOptions.IntegerRepresentation(second);
        return representation is null
            ? target
            : IrOptions.SetIntegerRepresentation(target, representation);
    }

    private static TypeExpr CloneType(TypeExpr type)
    {
        var clone = CloneUntagged(type);
        clone.Tag = type.Tag;
        return clone;
    }

    private bool IsConstructed(IrDocument document, IrModule module, TypeExpr type) => type switch
    {
        SequenceType or SetType or SequenceOfType or SetOfType or ChoiceType => true,
        RefType reference => Find(document, module, reference)?.Type is { } inner && IsConstructed(document, module, inner),
        _ => false
    };

    private IEnumerable<IrComponent> SortedSetComponents(
        IrDocument document,
        IrModule module,
        IReadOnlyList<IrComponent> components) =>
        components
            .Select((component, index) => (component, index, key: ComponentTagSortKey(document, module, component.Type)))
            .OrderBy(x => x.key.TagClass)
            .ThenBy(x => x.key.Number)
            .ThenBy(x => x.index)
            .Select(x => x.component);

    private (int TagClass, int Number) ComponentTagSortKey(IrDocument document, IrModule module, TypeExpr type)
    {
        type = UnwrapAliases(document, module, type);
        if (type.Tag is not null)
        {
            return (TagClassOrdinal(type.Tag.Class), type.Tag.Number);
        }

        return (0, UniversalTagNumber(document, module, type));
    }

    private static int TagClassOrdinal(string tagClass) => tagClass.ToLowerInvariant() switch
    {
        TagClasses.Universal => 0,
        TagClasses.Application => 1,
        TagClasses.Private => 3,
        _ => 2
    };

    private int UniversalTagNumber(IrDocument document, IrModule module, TypeExpr type) => type switch
    {
        BooleanType => 1,
        IntegerType => 2,
        BitStringType => 3,
        OctetStringType => 4,
        NullType => 5,
        OidType => 6,
        EnumeratedType => 10,
        StringType stringType => StringFormTagNumber(stringType.Form),
        TimeType timeType => timeType.Form == TimeTypes.Utc ? 23 : 24,
        SequenceType or SequenceOfType => 16,
        SetType or SetOfType => 17,
        RefType reference when Find(document, module, reference)?.Type is { } inner =>
            UniversalTagNumber(document, module, inner),
        _ => 16
    };

    private static int StringFormTagNumber(string form) => form switch
    {
        StringTypes.Utf8 => 12,
        StringTypes.Numeric => 18,
        StringTypes.Printable => 19,
        StringTypes.Teletex or StringTypes.T61 => 20,
        StringTypes.Videotex => 21,
        StringTypes.Ia5 => 22,
        StringTypes.Graphic => 25,
        StringTypes.Visible => 26,
        StringTypes.General => 27,
        StringTypes.Universal => 28,
        StringTypes.Bmp => 30,
        _ => throw new NotSupportedException($"Unknown stringType '{form}'.")
    };

    private static IrTypeDef? Find(IrDocument document, IrModule module, RefType reference) =>
        FindWithModule(document, module, reference)?.Def;

    private static (IrModule Module, IrTypeDef Def)? FindWithModule(
        IrDocument document,
        IrModule module,
        RefType reference)
    {
        var modules = string.IsNullOrEmpty(reference.Module)
            ? new[] { module }.Concat(document.Modules)
            : document.Modules.Where(m => m.Name == reference.Module);
        foreach (var candidate in modules)
        {
            var match = candidate.Types.FirstOrDefault(t => t.Name == reference.Name);
            if (match is not null)
            {
                return (candidate, match);
            }
        }

        return null;
    }

    private static TypeExpr CloneUntagged(TypeExpr type)
    {
        var clone = type switch
        {
            BooleanType => (TypeExpr)new BooleanType(),
            NullType => new NullType(),
            OctetStringType => new OctetStringType(),
            OidType => new OidType(),
            IntegerType integer => new IntegerType { NamedValues = integer.NamedValues },
            EnumeratedType enumerated => new EnumeratedType { Values = enumerated.Values },
            BitStringType bitString => new BitStringType { NamedBits = bitString.NamedBits },
            StringType stringType => new StringType { Form = stringType.Form },
            TimeType timeType => new TimeType { Form = timeType.Form, FractionDigits = timeType.FractionDigits },
            AnyType any => new AnyType { DefinedBy = any.DefinedBy },
            SequenceType sequence => new SequenceType { Components = sequence.Components },
            SetType set => new SetType { Components = set.Components, Extensible = set.Extensible },
            ChoiceType choice => new ChoiceType { Components = choice.Components },
            SequenceOfType sequenceOf => new SequenceOfType { Element = sequenceOf.Element },
            SetOfType setOf => new SetOfType { Element = setOf.Element },
            RefType reference => new RefType { Name = reference.Name, Module = reference.Module },
            _ => throw new NotSupportedException($"Cannot clone untagged type kind '{type.Kind}'.")
        };
        clone.Options = type.Options;
        clone.Constraint = type.Constraint;
        return clone;
    }

    private static string WriteCall(
        string writer,
        string tag,
        string expr,
        TypeExpr type) => type switch
    {
        BooleanType => $"{writer}.WriteBoolean({tag}, {expr})",
        IntegerType => $"{writer}.WriteInteger({tag}, {expr})",
        BitStringType => $"{writer}.WriteBitString({tag}, {expr})",
        OctetStringType => $"{writer}.WriteOctetString({tag}, {expr}.Span)",
        NullType => $"{writer}.WriteNull({tag})",
        OidType => $"{writer}.WriteObjectIdentifier({tag}, {expr})",
        StringType stringType => $"{writer}.WriteString({tag}, {expr}, {StringFormEnum(stringType.Form)})",
        TimeType timeType => timeType.Form == TimeTypes.Generalized
            ? $"{writer}.WriteTime({tag}, {expr}, {TimeFormEnum(timeType.Form)}, {timeType.FractionDigits ?? 3})"
            : $"{writer}.WriteTime({tag}, {expr}, {TimeFormEnum(timeType.Form)})",
        _ => throw new InvalidOperationException(type.Kind)
    };

    private static string ReadCall(
        string reader,
        string tag,
        TypeExpr type,
        string? integerRepresentation) => type switch
    {
        BooleanType => $"{reader}.ReadBoolean({tag})",
        IntegerType => IntegerReadCall(reader, tag, integerRepresentation),
        BitStringType => $"{reader}.ReadBitString({tag})",
        OctetStringType => $"{reader}.ReadOctetString({tag})",
        NullType => $"{reader}.ReadNull({tag})",
        OidType => $"{reader}.ReadObjectIdentifier({tag})",
        StringType stringType => $"{reader}.ReadString({tag}, {StringFormEnum(stringType.Form)})",
        TimeType timeType => $"{reader}.ReadTime({tag}, {TimeFormEnum(timeType.Form)})",
        _ => throw new InvalidOperationException(type.Kind)
    };

    private static string IntegerReadCall(string reader, string tag, string? representation) =>
        (representation ?? IrOptions.IntegerRepresentations.Der) switch
        {
            IrOptions.IntegerRepresentations.Int32 => $"{reader}.ReadInt32({tag})",
            IrOptions.IntegerRepresentations.UInt32 => $"{reader}.ReadUInt32({tag})",
            IrOptions.IntegerRepresentations.Int64 => $"{reader}.ReadInt64({tag})",
            IrOptions.IntegerRepresentations.UInt64 => $"{reader}.ReadUInt64({tag})",
            IrOptions.IntegerRepresentations.BigInt => $"{reader}.ReadInteger({tag})",
            IrOptions.IntegerRepresentations.Der => $"{reader}.ReadIntegerValue({tag})",
            _ => throw new NotSupportedException($"Unknown integer representation '{representation}'.")
        };

    private static string PropertyName(IrComponent field, string? enclosingTypeName = null)
    {
        var name = IrOptions.CSharpPropertyName(field.Options) ?? SanitizeIdentifier(field.Name);
        if (Keywords.Contains(name))
        {
            name = "@" + name;
        }

        if (enclosingTypeName is not null &&
            string.Equals(name, enclosingTypeName, StringComparison.Ordinal))
        {
            name += "Value";
        }

        return name;
    }

    private static string CamelCaseIdentifier(string identifier)
    {
        var name = identifier.StartsWith('@') ? identifier[1..] : identifier;
        if (name.Length == 0)
        {
            return "value";
        }

        var camel = char.ToLowerInvariant(name[0]) + name[1..];
        return Keywords.Contains(camel) ? "@" + camel : camel;
    }

    internal static string SanitizeIdentifier(string name)
    {
        var parts = name.Split(new[] { '-', '_' }, StringSplitOptions.RemoveEmptyEntries);
        var result = string.Concat(parts.Select(p => char.ToUpperInvariant(p[0]) + (p.Length > 1 ? p[1..] : "")));
        return string.IsNullOrEmpty(result) ? "Type" : result;
    }
