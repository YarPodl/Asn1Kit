    public string LanguageId => "csharp";

    public IReadOnlyList<GeneratedFile> Generate(IrDocument document)
    {
        // Overlay / hand-authored legacy any.bindings → selector + ref.openTypes (or definition-scoped modern).
        OpenTypeBindings.NormalizeLegacy(document);
        _carrierShapes.Clear();
        _carrierBindingNamesByModule.Clear();
        _emittedOpenCatalogs.Clear();
        foreach (var module in document.Modules)
        {
            if (!module.Types.Any(static type => IrOptions.ShouldGenerate(type.Options))) continue;
            CollectOpenCarrierShapes(document, module);
        }
        AssignOpenCarrierBindingStems();
        return document.Modules.Select(module => GenerateModule(document, module)).ToList();
    }

    private void CollectOpenCarrierShapes(IrDocument document, IrModule module)
    {
        var queue = new Queue<(string Name, TypeExpr Type)>();
        foreach (var type in module.Types)
        {
            if (!IrOptions.ShouldGenerate(type.Options)) continue;
            if (IsSignedSpecialization(type)) continue;
            if (IrOptions.CSharpAliasOf(type.Options) is not null) continue;
            var typeName = IrOptions.CSharpTypeName(type.Options) ?? SanitizeIdentifier(type.Name);
            if (IsCollapsibleAlias(type.Type))
            {
                CollectNested(document, module, typeName, type.Type, queue);
                continue;
            }
            queue.Enqueue((typeName, type.Type));
        }
        var emitted = new HashSet<string>(StringComparer.Ordinal);
        var nested = new List<(string Name, TypeExpr Type)>();
        while (queue.Count > 0)
        {
            var (name, type) = queue.Dequeue();
            if (!emitted.Add(name)) continue;
            CollectNested(document, module, name, type, queue);
            CollectOpenTypeUseNested(document, module, name, type, queue);
            nested.Add((name, type));
        }
        var plan = PlanOpenTypeWrappers(document, module, nested, emitted);
        RegisterOpenCarrierShapes(plan);
    }

    private GeneratedFile GenerateModule(IrDocument document, IrModule module)
    {
        _encodedDefaults.Clear();
        _defaultStorageName = SanitizeIdentifier(module.Name) + "Defaults";
        _nestedParents.Clear();
        _openTypeCodecCache = null;
        _knownOidExpressions = null;
        var ns = ModuleNamespace(module);
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Collections.Generic;");
        builder.AppendLine("using System.Globalization;");
        builder.AppendLine("using System.Numerics;");
        builder.AppendLine("using Asn1Kit.Runtime;");
        builder.AppendLine();
        builder.Append("namespace ").Append(ns).AppendLine(";");
        builder.AppendLine();

        var queue = new Queue<(string Name, TypeExpr Type)>();
        foreach (var type in module.Types)
        {
            if (!IrOptions.ShouldGenerate(type.Options))
            {
                continue;
            }

            if (IsSignedSpecialization(type))
            {
                continue;
            }
            if (IrOptions.CSharpAliasOf(type.Options) is not null)
            {
                continue;
            }
            var typeName = IrOptions.CSharpTypeName(type.Options) ?? SanitizeIdentifier(type.Name);
            if (IsCollapsibleAlias(type.Type))
            {
                // SEQUENCE OF / SET OF aliases collapse to T[], but nested element types
                // (e.g. SEQUENCE OF SEQUENCE {…}) must still be emitted as Owner_Item.
                CollectNested(document, module, typeName, type.Type, queue);
                continue;
            }

            queue.Enqueue((typeName, type.Type));
        }

        var emitted = new HashSet<string>(StringComparer.Ordinal);
        var nested = new List<(string Name, TypeExpr Type)>();
        while (queue.Count > 0)
        {
            var (name, type) = queue.Dequeue();
            if (!emitted.Add(name))
            {
                continue;
            }

            CollectNested(document, module, name, type, queue);
            CollectOpenTypeUseNested(document, module, name, type, queue);
            nested.Add((name, type));
        }

        var oidValues = CollectOidValues(module);
        var openWrappers = PlanOpenTypeWrappers(document, module, nested, emitted);
        foreach (var wrapper in openWrappers.Wrappers)
        {
            OfferNested(document, module, wrapper.Name + "_Value", wrapper.Binding.Type, queue);
            if (wrapper.Site.Payload.Child is null)
            {
                var alternatives = ExpandOpenTypeChoice(document, module, module, null,
                    wrapper.Binding.Type, null, new HashSet<ChoiceType>()).ToList();
                if (alternatives.Count > 1)
                    foreach (var (name, type, _) in alternatives)
                        OfferNested(document, module, wrapper.Name + "_" + OpenDecodedHint(name), type, queue);
            }
        }
        while (queue.Count > 0)
        {
            var (name, type) = queue.Dequeue();
            if (!emitted.Add(name)) continue;
            CollectNested(document, module, name, type, queue);
            nested.Add((name, type));
        }
        var apiNames = new HashSet<string>(emitted, StringComparer.Ordinal) { OidCatalogName(module) };
        foreach (var wrapper in openWrappers.Wrappers)
        {
            apiNames.Add(wrapper.Name);
            apiNames.Add(wrapper.Name + "BindingCodec");
        }
        AssignOpenWrapperApiNames(openWrappers, apiNames);
        PlanOpenTypeUses(document, module, nested, apiNames, openWrappers);
        if (oidValues.Count > 0)
        {
            var catalogName = OidCatalogName(module);
            if (emitted.Contains(catalogName))
            {
                throw new NotSupportedException(
                    $"Generated OID catalog '{catalogName}' in module '{module.Name}' conflicts with a generated type.");
            }

            EmitOidCatalog(builder, module, oidValues);
            builder.AppendLine();
        }

        PlanDecodeContexts(nested);
        if (document.Modules.SelectMany(m => m.Types).Any(t => IsSignedSpecialization(t) && t.Specialization!.Module == module.Name))
        {
            EmitSignedBase(builder);
        }
        foreach (var (name, type) in nested)
        {
            EmitType(builder, document, module, name, type);
            builder.AppendLine();
        }
        foreach (var definition in module.Types.Where(IsSignedSpecialization))
        {
            EmitSignedSpecialization(builder, document, module, definition);
            builder.AppendLine();
        }
        AssignOpenTypeUseMemberCodecs(document, module);
        AssignOpenCodecExpressions(document, module, openWrappers);
        EmitOpenTypeCodecCache(builder, document, module);
        EmitOpenTypeUseDescriptors(builder, document, module);
        EmitOpenTypeWrappers(builder, document, module, openWrappers);
        EmitEncodedDefaults(builder, module);

        return new GeneratedFile(SanitizeIdentifier(module.Name) + ".g.cs", builder.ToString());
    }

    private static bool IsSignedSpecialization(IrTypeDef definition) =>
        definition.Specialization is { Name: "SIGNED" } &&
        definition.Type is SequenceType { Components.Count: 3, Extensible: false, Tag: null } sequence &&
        sequence.Components[0] is { Name: "toBeSigned", Optional: false } &&
        sequence.Components[1] is { Name: "algorithmIdentifier", Optional: false,
            Type: SequenceType { Components.Count: 2, Extensible: false, Tag: null } } &&
        sequence.Components[1].Type is SequenceType algorithm &&
        algorithm.Components[0] is { Name: "algorithm", Optional: false, Type: OidType { Tag: null } } &&
        algorithm.Components[1] is { Name: "parameters", Optional: true, Type: AnyType { Tag: null } } &&
        sequence.Components[2] is { Name: "signature", Optional: false, Type: BitStringType { Tag: null } };

    private static void EmitSignedBase(StringBuilder sb)
    {
        sb.AppendLine("public sealed class SignedAlgorithmIdentifier");
        sb.AppendLine("{");
        sb.AppendLine("    public Asn1Oid Algorithm { get; set; }");
        sb.AppendLine("    public Asn1Any? Parameters { get; set; }");
        sb.AppendLine("    public void Encode(Asn1Writer writer)");
        sb.AppendLine("    {");
        sb.AppendLine("        using (writer.EnterSequence(Asn1Tag.Sequence))");
        sb.AppendLine("        {");
        sb.AppendLine("            writer.WriteObjectIdentifier(Asn1Tag.ObjectIdentifier, Algorithm);");
        sb.AppendLine("            if (Parameters is { } parameters) writer.WriteAny(parameters);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("    public static SignedAlgorithmIdentifier Decode(Asn1Reader reader)");
        sb.AppendLine("    {");
        sb.AppendLine("        using (reader.EnterSequence(Asn1Tag.Sequence))");
        sb.AppendLine("        {");
        sb.AppendLine("            var value = new SignedAlgorithmIdentifier { Algorithm = reader.ReadOid(Asn1Tag.ObjectIdentifier) };");
        sb.AppendLine("            if (!reader.Eof) value.Parameters = reader.ReadAny();");
        sb.AppendLine("            reader.ThrowIfNotEmpty();");
        sb.AppendLine("            return value;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("public abstract class Signed<T>");
        sb.AppendLine("{");
        sb.AppendLine("    public T ToBeSigned { get; set; } = default!;");
        sb.AppendLine("    public SignedAlgorithmIdentifier AlgorithmIdentifier { get; set; } = new();");
        sb.AppendLine("    public Asn1BitString Signature { get; set; }");
        sb.AppendLine("    public void Encode(Asn1Writer writer) => Encode(writer, Asn1Tag.Sequence);");
        sb.AppendLine("    public void Encode(Asn1Writer writer, Asn1Tag tag)");
        sb.AppendLine("    {");
        sb.AppendLine("        using (writer.EnterSequence(tag))");
        sb.AppendLine("        {");
        sb.AppendLine("            EncodeToBeSigned(writer);");
        sb.AppendLine("            AlgorithmIdentifier.Encode(writer);");
        sb.AppendLine("            writer.WriteBitString(Asn1Tag.BitString, Signature);");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("    protected abstract void EncodeToBeSigned(Asn1Writer writer);");
        sb.AppendLine("    protected static void DecodeTail(Asn1Reader reader, Signed<T> value)");
        sb.AppendLine("    {");
        sb.AppendLine("        value.AlgorithmIdentifier = SignedAlgorithmIdentifier.Decode(reader);");
        sb.AppendLine("        value.Signature = reader.ReadBitString(Asn1Tag.BitString);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private void EmitSignedSpecialization(StringBuilder sb, IrDocument document, IrModule module, IrTypeDef definition)
    {
        var sequence = (SequenceType)definition.Type;
        var name = IrOptions.CSharpTypeName(definition.Options) ?? SanitizeIdentifier(definition.Name);
        var tbs = sequence.Components[0].Type;
        var retainTbs = ShouldEmitRetainEncoded(document, module, tbs, sequence.Components[0].Options);
        var tbsType = CsType(document, module, name, "ToBeSigned", tbs, false);
        var origin = document.Modules.Single(m => m.Name == definition.Specialization!.Module);
        var baseName = ModuleNamespace(origin) + ".Signed<" + tbsType + ">";
        sb.AppendLine($"public sealed class {name} : {baseName}");
        sb.AppendLine("{");
        if (retainTbs)
            sb.AppendLine("    public ReadOnlyMemory<byte> ToBeSignedOriginalEncoding { get; private set; }");
        sb.AppendLine("    protected override void EncodeToBeSigned(Asn1Writer writer)");
        sb.AppendLine("    {");
        EmitEncodeValue(sb, document, module, name, "ToBeSigned", tbs, "        ", "writer", "ToBeSigned");
        sb.AppendLine("    }");
        sb.AppendLine($"    public static {name} Decode(Asn1Reader reader) => Decode(reader, DefaultTag);");
        sb.AppendLine($"    public static {name} Decode(Asn1Reader reader, Asn1Tag tag)");
        sb.AppendLine("    {");
        sb.AppendLine("        using (reader.EnterSequence(tag))");
        sb.AppendLine("        {");
        sb.AppendLine($"            var value = new {name}();");
        if (retainTbs)
        {
            sb.Append("            var retained = reader.ReadWithOriginalEncoding(r => ");
            EmitDecodeExpr(sb, document, module, name, "ToBeSigned", tbs, "r");
            sb.AppendLine(");");
            sb.AppendLine("            value.ToBeSigned = retained.Value;");
            sb.AppendLine("            value.ToBeSignedOriginalEncoding = retained.OriginalEncoding;");
        }
        else
        {
            sb.Append("            value.ToBeSigned = ");
            EmitDecodeExpr(sb, document, module, name, "ToBeSigned", tbs, "reader");
            sb.AppendLine(";");
        }
        sb.AppendLine("            DecodeTail(reader, value);");
        sb.AppendLine("            reader.ThrowIfNotEmpty();");
        sb.AppendLine("            return value;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("    public static Asn1Tag DefaultTag { get; } = Asn1Tag.Sequence;");
        sb.AppendLine("}");
    }

    private static List<(IrValueDef Definition, IrOidValue Value, string Member)> CollectOidValues(IrModule module)
    {
        var result = new List<(IrValueDef Definition, IrOidValue Value, string Member)>();
        var generatedNames = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var definition in module.Values)
        {
            if (definition.Value is not IrOidValue value || !IrOptions.ShouldGenerate(definition.Options))
            {
                continue;
            }

            var member = SanitizeIdentifier(definition.Name);
            ReserveOidMemberName(generatedNames, member, definition.Name, module.Name);
            ReserveOidMemberName(generatedNames, member + "String", definition.Name, module.Name);
            ReserveOidMemberName(generatedNames, member + "Cache", definition.Name, module.Name);
            result.Add((definition, value, member));
        }

        return result;
    }

    private static void ReserveOidMemberName(
        Dictionary<string, string> generatedNames,
        string generatedName,
        string asnName,
        string moduleName)
    {
        if (generatedNames.TryGetValue(generatedName, out var existing))
        {
            throw new NotSupportedException(
                $"OID values '{existing}' and '{asnName}' in module '{moduleName}' generate conflicting C# member " +
                $"'{generatedName}'.");
        }

        generatedNames.Add(generatedName, asnName);
    }

    private static void EmitOidCatalog(
        StringBuilder sb,
        IrModule module,
        IReadOnlyList<(IrValueDef Definition, IrOidValue Value, string Member)> values)
    {
        sb.AppendLine($"public static class {OidCatalogName(module)}");
        sb.AppendLine("{");
        for (var i = 0; i < values.Count; i++)
        {
            var (definition, value, member) = values[i];
            sb.AppendLine($"    /// <summary>ASN.1 OBJECT IDENTIFIER {definition.Name}.</summary>");
            sb.AppendLine($"    public const string {member}String = \"{EscapeCSharpString(value.Value)}\";");
            sb.AppendLine($"    public static Asn1Oid {member} => {member}Cache.Value;");
            sb.AppendLine();
            sb.AppendLine($"    private static class {member}Cache");
            sb.AppendLine("    {");
            sb.AppendLine($"        internal static readonly Asn1Oid Value = Asn1Oid.Parse({member}String);");
            sb.AppendLine("    }");
            if (i + 1 < values.Count)
            {
                sb.AppendLine();
            }
        }

        sb.AppendLine("}");
    }

    private static string OidCatalogName(IrModule module) =>
        SanitizeIdentifier(module.Name) + "Oids";

    private Dictionary<(string Dotted, bool QualifyLocal), string?>? _knownOidExpressions;

    private string? KnownOidExpression(IrDocument document, IrModule module, string dottedValue,
        bool qualifyLocal = false)
    {
        _knownOidExpressions ??= new Dictionary<(string Dotted, bool QualifyLocal), string?>();
        var cacheKey = (dottedValue, qualifyLocal);
        if (_knownOidExpressions.TryGetValue(cacheKey, out var cached)) return cached;

        // Prefer the local catalog, then imported modules, then the rest of the generated document.
        // Table specialization can carry keys from a module without directly importing its OID values.
        var candidates = new[] { module }
            .Concat(module.Imports.Select(import => document.Modules.FirstOrDefault(m => m.Name == import.Module))
                .OfType<IrModule>())
            .Concat(document.Modules).Distinct();
        string? expression = null;
        foreach (var candidate in candidates)
        {
            foreach (var definition in candidate.Values)
            {
                if (definition.Value is not IrOidValue value || !IrOptions.ShouldGenerate(definition.Options) ||
                    !string.Equals(value.Value, dottedValue, StringComparison.Ordinal)) continue;
                expression = OidCatalogName(candidate) + "." + SanitizeIdentifier(definition.Name);
                expression = candidate == module
                    ? (qualifyLocal ? ModuleNamespace(module) + "." : "") + expression
                    : "global::" + ModuleNamespace(candidate) + "." + expression;
                break;
            }
            if (expression is not null) break;
        }

        _knownOidExpressions[cacheKey] = expression;
        return expression;
    }

    private void CollectNested(
        IrDocument document,
        IrModule module,
        string owner,
        TypeExpr type,
        Queue<(string Name, TypeExpr Type)> queue)
    {
        switch (type)
        {
            case OctetStringType { Containing: { } content }:
                OfferNested(document, module, owner + "_Content", content, queue);
                break;
            case BitStringType { Containing: { } bitContent }:
                OfferNested(document, module, owner + "_Content", bitContent, queue);
                break;
            case SequenceType sequence:
                foreach (var component in sequence.Components)
                {
                    RegisterNestedParent(owner, sequence.Components, component);
                    OfferNested(document, module, owner + "_" + SanitizeIdentifier(component.Name), component.Type, queue);
                }

                break;
            case SetType set:
                foreach (var component in set.Components)
                {
                    RegisterNestedParent(owner, set.Components, component);
                    OfferNested(document, module, owner + "_" + SanitizeIdentifier(component.Name), component.Type, queue);
                }

                break;
            case ChoiceType choice:
                if (IsSingleAlternativeChoice(choice))
                {
                    // Transparent: nested types are named as if the CHOICE wrapper were absent.
                    OfferNested(document, module, owner, choice.Components[0].Type, queue);
                }
                else
                {
                    foreach (var component in choice.Components)
                    {
                        RegisterNestedParent(owner, choice.Components, component);
                        OfferNested(
                            document,
                            module,
                            owner + "_" + SanitizeIdentifier(component.Name),
                            component.Type,
                            queue);
                    }
                }

                break;
            case SequenceOfType sequenceOf:
                OfferNested(document, module, owner + "_Item", sequenceOf.Element, queue);
                break;
            case SetOfType setOf:
                OfferNested(document, module, owner + "_Item", setOf.Element, queue);
                break;
        }
    }

    private void OfferNested(
        IrDocument document,
        IrModule module,
        string hint,
        TypeExpr type,
        Queue<(string Name, TypeExpr Type)> queue)
    {
        if (NeedsNamedType(type) || IsEnumerated(type) || IsNamedInteger(type))
        {
            queue.Enqueue((hint, WithoutTag(type)));
            if (NeedsNamedType(type))
            {
                CollectNested(document, module, hint, WithoutTag(type), queue);
            }
        }
        else if (type is RefType)
        {
            return;
        }
        else if (ContainedType(type) is { } content)
        {
            OfferNested(document, module, hint + "_Content", content, queue);
        }
        else if (type is SequenceOfType or SetOfType or SequenceType or SetType or ChoiceType)
        {
            CollectNested(document, module, hint, type, queue);
        }
    }

    private static TypeExpr WithoutTag(TypeExpr type)
    {
        // Nested class uses the inner encoding; the field's tag is applied by the parent.
        type.Tag = type.Tag;
        return type;
    }

    private static bool NeedsNamedType(TypeExpr type) =>
        type is SequenceType or SetType
        || (type is ChoiceType && !IsSingleAlternativeChoice(type));

    /// <summary>
    /// CHOICE with one alternative encodes as that alternative; collapse like a typedef alias.
    /// Keep a real CHOICE class when both the CHOICE and the alternative carry tags (double wrap).
    /// </summary>
    private static bool IsSingleAlternativeChoice(TypeExpr type) =>
        type is ChoiceType { Components: { Count: 1 } } choice
        && !choice.Extensible
        && (choice.Tag is null || choice.Components[0].Type.Tag is null);

    private static bool IsNamedBitString(TypeExpr type) =>
        type is BitStringType { NamedBits: { Count: > 0 } };

    private static bool IsEnumerated(TypeExpr type) => type is EnumeratedType;

    private static bool IsNamedInteger(TypeExpr type) =>
        type is IntegerType { NamedValues: { Count: > 0 } };

    /// <summary>Typedefs that must not get their own C# class (collapsed to the underlying type).</summary>
    private static bool IsCollapsibleAlias(TypeExpr type) =>
        !NeedsNamedType(type) && !IsNamedBitString(type) && !IsEnumerated(type) && !IsNamedInteger(type);

    private void EmitType(StringBuilder sb, IrDocument document, IrModule module, string typeName, TypeExpr type)
    {
        EnsureBackendSupport(type);
        switch (type)
        {
            case SequenceType sequence:
                EmitSequence(sb, document, module, typeName, sequence);
                break;
            case SetType set:
                EmitSet(sb, document, module, typeName, set);
                break;
            case ChoiceType choice:
                EmitChoice(sb, document, module, typeName, choice);
                break;
            case SequenceOfType:
            case SetOfType:
                throw new NotSupportedException(
                    $"C# backend does not emit a named type for '{type.Kind}'; use T[] via field encode/decode.");
            case BitStringType bitString when IsNamedBitString(bitString):
                EmitNamedBitString(sb, typeName, bitString);
                break;
            case EnumeratedType enumerated:
                EmitEnumerated(sb, typeName, enumerated);
                break;
            case IntegerType integer when IsNamedInteger(integer):
                EmitNamedIntegerConstants(sb, typeName, integer);
                break;
            default:
                throw new InvalidOperationException(
                    $"C# backend refused to emit collapsible alias '{typeName}' (kind '{type.Kind}').");
        }
    }

    private static void EnsureBackendSupport(TypeExpr type)
    {
        switch (type)
        {
            case SequenceType sequence:
                foreach (var component in sequence.Components)
                {
                    EnsureBackendSupport(component.Type);
                }

                break;
            case SetType set:
                foreach (var component in set.Components)
                {
                    EnsureBackendSupport(component.Type);
                }

                break;
            case ChoiceType choice:
                foreach (var component in choice.Components)
                {
                    EnsureBackendSupport(component.Type);
                }

                break;
            case SequenceOfType sequenceOf:
                EnsureBackendSupport(sequenceOf.Element);
                break;
            case SetOfType setOf:
                EnsureBackendSupport(setOf.Element);
                break;
            case AnyType any when any.Bindings is { Count: > 0 }:
                foreach (var binding in any.Bindings)
                {
                    EnsureBackendSupport(binding.Type);
                }

                break;
        }
    }

    private bool EmitStructuredTypeShell(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string typeName,
        TypeExpr type,
        IReadOnlyList<IrComponent> components)
    {
        var valueType = IsCSharpValueTypeEmit(module, typeName, type);
        var typeKeyword = valueType ? "struct" : "sealed class";
        sb.AppendLine($"public {typeKeyword} {typeName}");
        sb.AppendLine("{");
        EmitCachedDefaults(sb, document, module, typeName, components);
        foreach (var field in components)
        {
            EmitProperty(
                sb,
                document,
                module,
                typeName,
                field,
                (field.Optional || field.ExtensionAddition == true) && field.Default is null,
                privateSetter: false);
        }

        if (valueType) EmitStructConstructor(sb, document, module, typeName, components);
        return valueType;
    }

    private void EmitStructuredEncode(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string typeName,
        IReadOnlyList<IrComponent> components,
        IEnumerable<IrComponent> encodeOrder,
        bool valueType,
        bool extensible,
        string enterMethod)
    {
        sb.AppendLine();
        sb.AppendLine("    public void Encode(Asn1Writer writer) => Encode(writer, DefaultTag);");
        sb.AppendLine();
        sb.AppendLine("    public void Encode(Asn1Writer writer, Asn1Tag tag)");
        sb.AppendLine("    {");
        if (valueType)
        {
            foreach (var field in components)
            {
                var prop = PropertyName(field, typeName);
                var local = "enc_" + prop.TrimStart('@');
                sb.AppendLine($"        var {local} = {prop};");
            }
        }

        sb.AppendLine($"        using (writer.{enterMethod}(tag))");
        sb.AppendLine("        {");
        if (extensible)
            EmitExtensionGroupChecks(sb, document, module, typeName, components, "            ", null);
        foreach (var field in encodeOrder)
        {
            if (valueType)
            {
                var prop = PropertyName(field, typeName);
                var local = "enc_" + prop.TrimStart('@');
                EmitEncodeFieldFromExpr(
                    sb,
                    document,
                    module,
                    typeName,
                    field,
                    "            ",
                    "writer",
                    local);
            }
            else
            {
                EmitEncodeField(sb, document, module, typeName, field, "            ", "writer");
            }
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
    }

    private void EmitSequence(StringBuilder sb, IrDocument document, IrModule module, string typeName, SequenceType type)
    {
        var valueType = EmitStructuredTypeShell(sb, document, module, typeName, type, type.Components);
        EmitStructuredEncode(
            sb, document, module, typeName, type.Components, type.Components, valueType, type.Extensible, "EnterSequence");
        sb.AppendLine();
        sb.AppendLine($"    public static {typeName} Decode(Asn1Reader reader) => Decode(reader, DefaultTag);");
        sb.AppendLine();
        EmitDecodeContextHeader(sb, typeName, true);
        sb.AppendLine("    {");
        sb.AppendLine("        using (reader.EnterSequence(tag))");
        sb.AppendLine("        {");
        sb.AppendLine($"            var value = new {typeName}();");
        if (type.Extensible) EmitSequenceExtensionDecode(sb, document, module, typeName, type, "            ");
        else foreach (var field in type.Components)
        {
            EmitDecodeField(
                sb, document, module, typeName, field, type.Components, "            ", "reader", "value");
        }

        sb.AppendLine("            reader.ThrowIfNotEmpty();");
        sb.AppendLine("            return value;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        EmitDefaultTag(sb, type, constructed: true, fallback: "Asn1Tag.Sequence");
        sb.AppendLine("}");
    }

    private void EmitSet(StringBuilder sb, IrDocument document, IrModule module, string typeName, SetType type)
    {
        var deferredFields = type.Components.Where(f =>
            _contextDepth.GetValueOrDefault(typeName + "_" + SanitizeIdentifier(f.Name)) > 0 ||
            _contextDepth.GetValueOrDefault(typeName + "_" + SanitizeIdentifier(f.Name) + "_Item") > 0).ToHashSet();
        var valueType = EmitStructuredTypeShell(sb, document, module, typeName, type, type.Components);
        EmitStructuredEncode(
            sb,
            document,
            module,
            typeName,
            type.Components,
            SortedSetComponents(document, module, type.Components),
            valueType,
            type.Extensible,
            type.Extensible ? "EnterSetOf" : "EnterSet");
        sb.AppendLine();
        sb.AppendLine($"    public static {typeName} Decode(Asn1Reader reader) => Decode(reader, DefaultTag);");
        sb.AppendLine();
        EmitDecodeContextHeader(sb, typeName, true);
        sb.AppendLine("    {");
        sb.AppendLine("        using (reader.EnterSet(tag))");
        sb.AppendLine("        {");
        sb.AppendLine($"            var value = new {typeName}();");
        foreach (var field in type.Components)
        {
            if (!field.Optional || field.Default is not null || deferredFields.Contains(field))
            {
                sb.AppendLine($"            var seen_{SanitizeIdentifier(field.Name)} = false;");
            }
            if (deferredFields.Contains(field)) sb.AppendLine($"            Asn1Any? deferred_{SanitizeIdentifier(field.Name)} = null;");
        }

        sb.AppendLine("            while (!reader.Eof)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (!reader.TryPeekTag(out var peeked))");
        sb.AppendLine("                {");
        sb.AppendLine("                    break;");
        sb.AppendLine("                }");
        var first = true;
        foreach (var field in type.Components)
        {
            var prop = PropertyName(field, typeName);
            var cond = first ? "if" : "else if";
            first = false;
            sb.AppendLine($"                {cond} ({PeekMatchExpr(document, module, field.Type, "peeked")})");
            sb.AppendLine("                {");
            if (!field.Optional || field.Default is not null || deferredFields.Contains(field))
            {
                var seen = $"seen_{SanitizeIdentifier(field.Name)}";
                sb.AppendLine($"                    if ({seen}) throw new Asn1Exception(\"Duplicate SET component '{field.Name}'.\");");
                sb.AppendLine($"                    {seen} = true;");
            }
            else
            {
                sb.AppendLine($"                    if (value.{prop} != null) throw new Asn1Exception(\"Duplicate SET component '{field.Name}'.\");");
            }

            if (deferredFields.Contains(field))
                sb.AppendLine($"                    deferred_{SanitizeIdentifier(field.Name)} = reader.ReadAny();");
            else EmitDecodeAssign(
                sb,
                document,
                module,
                typeName,
                field.Name,
                field.Type,
                type.Components,
                "                    ",
                "reader",
                $"value.{prop}",
                targetObject: "value");
            sb.AppendLine("                }");
        }

        if (type.Extensible)
            sb.AppendLine("                else _ = reader.ReadAny();");
        else sb.AppendLine("                else throw new Asn1Exception(\"Unknown SET component.\");");
        sb.AppendLine("            }");
        foreach (var field in type.Components)
        {
            if (!field.Optional && field.ExtensionAddition != true && field.Default is null)
            {
                sb.AppendLine(
                    $"            if (!seen_{SanitizeIdentifier(field.Name)}) throw new Asn1Exception(\"Missing SET component '{field.Name}'.\");");
            }
        }

        foreach (var field in deferredFields)
        {
            var deferred = "deferred_" + SanitizeIdentifier(field.Name);
            sb.AppendLine($"            if ({deferred}.HasValue)");
            sb.AppendLine($"            {{");
            sb.AppendLine($"                using (reader.EnterEncoded({deferred}.Value.EncodedMemory))");
            sb.AppendLine($"                {{");
            EmitDecodeAssign(sb, document, module, typeName, field.Name, field.Type, type.Components, "                    ", "reader", "value." + PropertyName(field, typeName), targetObject: "value", fieldOptions: field.Options);
            sb.AppendLine("                    reader.ThrowIfNotEmpty();");
            sb.AppendLine("                }");
            sb.AppendLine("            }");
        }

        if (type.Extensible)
            EmitExtensionGroupChecks(sb, document, module, typeName, type.Components, "            ", "value");

        sb.AppendLine("            return value;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        EmitDefaultTag(sb, type, constructed: true, fallback: "Asn1Tag.Set");
        sb.AppendLine("}");
    }

    private void EmitChoice(StringBuilder sb, IrDocument document, IrModule module, string typeName, ChoiceType type)
    {
        var homogeneousCsType = TryHomogeneousChoiceCsType(document, module, typeName, type);

        sb.AppendLine($"public enum {typeName}Kind");
        sb.AppendLine("{");
        foreach (var field in type.Components)
        {
            sb.AppendLine($"    {PropertyName(field, typeName)},");
        }
        if (type.Extensible) sb.AppendLine("    Unknown,");

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"public sealed class {typeName}");
        sb.AppendLine("{");
        sb.AppendLine($"    public {typeName}Kind Kind {{ get; private set; }}");
        if (type.Extensible)
        {
            sb.AppendLine("    public Asn1Any? Unknown { get; private set; }");
            sb.AppendLine($"    public static {typeName} FromUnknown(Asn1Any value) => new {typeName} {{ Kind = {typeName}Kind.Unknown, Unknown = value }};");
        }
        if (homogeneousCsType is not null)
        {
            var valueInit = Initializer(
                document, module, typeName, type.Components[0].Name, type.Components[0].Type, optional: false);
            sb.AppendLine($"    public {homogeneousCsType} Value {{ get; private set; }}{valueInit}");
        }
        else
        {
            foreach (var field in type.Components)
            {
                EmitProperty(sb, document, module, typeName, field, optional: true, privateSetter: true);
            }
        }

        sb.AppendLine();
        foreach (var field in type.Components)
        {
            var prop = PropertyName(field, typeName);
            var factoryName = prop.StartsWith('@') ? prop[1..] : prop;
            var csType = homogeneousCsType
                ?? CsType(document, module, typeName, field.Name, field.Type, optional: false, field.Options);
            var param = CamelCaseIdentifier(prop);
            var assignProp = homogeneousCsType is not null ? "Value" : prop;
            sb.AppendLine($"    public static {typeName} From{factoryName}({csType} {param}) => new {typeName}");
            sb.AppendLine("    {");
            sb.AppendLine($"        Kind = {typeName}Kind.{prop},");
            sb.AppendLine($"        {assignProp} = {param},");
            sb.AppendLine("    };");
            sb.AppendLine();
        }

        sb.AppendLine("    public override string ToString()");
        sb.AppendLine("    {");
        sb.AppendLine("        return Kind switch");
        sb.AppendLine("        {");
        foreach (var field in type.Components)
        {
            var prop = PropertyName(field, typeName);
            var access = homogeneousCsType is not null ? "Value" : prop;
            sb.AppendLine($"            {typeName}Kind.{prop} => Asn1Formatting.Format({access}),");
        }
        sb.AppendLine("            _ => \"<unset>\",");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public void Encode(Asn1Writer writer)");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (Kind)");
        sb.AppendLine("        {");
        foreach (var field in type.Components)
        {
            var prop = PropertyName(field, typeName);
            var encodeExpr = homogeneousCsType is not null
                ? "Value"
                : UnwrapOptional(document, module, field.Type, prop, field.Options);
            sb.AppendLine($"            case {typeName}Kind.{prop}:");
            EmitEncodeValue(
                sb,
                document,
                module,
                typeName,
                field.Name,
                field.Type,
                "                ",
                "writer",
                encodeExpr,
                fieldOptions: field.Options);
            sb.AppendLine("                break;");
        }

        if (type.Extensible)
        {
            sb.AppendLine($"            case {typeName}Kind.Unknown:");
            sb.AppendLine("                writer.WriteAny(Unknown ?? throw new Asn1Exception(\"Missing unknown CHOICE value.\"));");
            sb.AppendLine("                break;");
        }
        sb.AppendLine("            default: throw new Asn1Exception(\"CHOICE has no alternative.\");");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        EmitDecodeContextHeader(sb, typeName, false);
        sb.AppendLine("    {");
        sb.AppendLine("        if (!reader.TryPeekTag(out var peeked)) throw new Asn1Exception(\"Empty CHOICE.\");");
        sb.AppendLine($"        var value = new {typeName}();");
        var first = true;
        foreach (var field in type.Components)
        {
            var prop = PropertyName(field, typeName);
            var assignTarget = homogeneousCsType is not null ? "value.Value" : $"value.{prop}";
            var cond = first ? "if" : "else if";
            first = false;
            sb.AppendLine($"        {cond} (peeked.MatchesIgnoreConstructed({TagExpr(document, module, field.Type)}))");
            sb.AppendLine("        {");
            sb.AppendLine($"            value.Kind = {typeName}Kind.{prop};");
            EmitDecodeAssign(
                sb,
                document,
                module,
                typeName,
                field.Name,
                field.Type,
                ownerComponents: null,
                "            ",
                "reader",
                assignTarget,
                fieldOptions: field.Options);
            sb.AppendLine("        }");
        }

        if (type.Extensible) sb.AppendLine("        else return FromUnknown(reader.ReadAny());");
        else sb.AppendLine("        else throw new Asn1Exception(\"Unknown CHOICE alternative.\");");
        sb.AppendLine("        return value;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    /// <summary>
    /// When every alternative maps to the same non-nullable CLR type, collapse alt properties into one Value.
    /// </summary>
    private string? TryHomogeneousChoiceCsType(
        IrDocument document,
        IrModule module,
        string typeName,
        ChoiceType type)
    {
        if (type.Components.Count < 2)
        {
            return null;
        }

        string? shared = null;
        foreach (var field in type.Components)
        {
            var csType = CsType(document, module, typeName, field.Name, field.Type, optional: false, field.Options);
            if (shared is null)
            {
                shared = csType;
            }
            else if (!string.Equals(shared, csType, StringComparison.Ordinal))
            {
                return null;
            }
        }

        return shared;
    }

    private void EmitNamedBitString(StringBuilder sb, string typeName, BitStringType type)
    {
        var namedBits = type.NamedBits!;
        var maxIndex = namedBits.Max(b => b.Value);
        if (maxIndex > 62)
        {
            throw new NotSupportedException(
                $"Named BIT STRING '{typeName}' bit index {maxIndex} exceeds Flags enum limit (62).");
        }

        var useLong = maxIndex > 30;
        var enumName = typeName + "Flags";
        var shiftSuffix = useLong ? "L" : "";

        sb.AppendLine("[Flags]");
        sb.Append("public enum ").Append(enumName);
        if (useLong)
        {
            sb.Append(" : long");
        }

        sb.AppendLine();
        sb.AppendLine("{");
        sb.AppendLine("    None = 0,");
        for (var i = 0; i < namedBits.Count; i++)
        {
            var bit = namedBits[i];
            var member = SanitizeIdentifier(bit.Name);
            sb.AppendLine(
                $"    /// <summary>ASN.1 named bit {bit.Name}({bit.Value.ToString(CultureInfo.InvariantCulture)}).</summary>");
            sb.Append($"    {member} = 1{shiftSuffix} << {bit.Value.ToString(CultureInfo.InvariantCulture)}");
            sb.AppendLine(i + 1 < namedBits.Count ? "," : "");
        }

        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine($"public sealed class {typeName}");
        sb.AppendLine("{");
        sb.AppendLine("    public Asn1BitString Value { get; set; }");
        sb.AppendLine();
        sb.AppendLine($"    public {enumName} Flags");
        sb.AppendLine("    {");
        sb.AppendLine("        get => ToFlags(Value);");
        sb.AppendLine("        set => Value = FromFlags(value);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    public static {enumName} ToFlags(Asn1BitString bits)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var flags = {enumName}.None;");
        foreach (var bit in namedBits)
        {
            var member = SanitizeIdentifier(bit.Name);
            var index = bit.Value.ToString(CultureInfo.InvariantCulture);
            sb.AppendLine(
                $"        if (bits.BitLength > {index} && bits[{index}]) flags |= {enumName}.{member};");
        }

        sb.AppendLine("        return flags;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    public static Asn1BitString FromFlags({enumName} flags)");
        sb.AppendLine("    {");
        var length = ((int)maxIndex + 1).ToString(CultureInfo.InvariantCulture);
        sb.AppendLine($"        var bits = new bool[{length}];");
        foreach (var bit in namedBits)
        {
            var member = SanitizeIdentifier(bit.Name);
            var index = bit.Value.ToString(CultureInfo.InvariantCulture);
            sb.AppendLine(
                $"        if ((flags & {enumName}.{member}) != 0) bits[{index}] = true;");
        }

        sb.AppendLine("        var length = bits.Length;");
        sb.AppendLine("        while (length > 0 && !bits[length - 1])");
        sb.AppendLine("        {");
        sb.AppendLine("            length--;");
        sb.AppendLine("        }");
        sb.AppendLine("        return Asn1BitString.FromBits(bits.AsSpan(0, length));");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public void Encode(Asn1Writer writer) => Encode(writer, DefaultTag);");
        sb.AppendLine();
        sb.AppendLine("    public void Encode(Asn1Writer writer, Asn1Tag tag)");
        sb.AppendLine("    {");
        sb.AppendLine("        writer.WriteBitString(tag, Value);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    public static {typeName} Decode(Asn1Reader reader) => Decode(reader, DefaultTag);");
        sb.AppendLine();
        sb.AppendLine($"    public static {typeName} Decode(Asn1Reader reader, Asn1Tag tag)");
        sb.AppendLine("    {");
        sb.AppendLine($"        return new {typeName} {{ Value = reader.ReadBitString(tag) }};");
        sb.AppendLine("    }");
        EmitDefaultTag(sb, type, constructed: false, fallback: "Asn1Tag.BitString");
        sb.AppendLine("}");
    }

    private void EmitEnumerated(StringBuilder sb, string typeName, EnumeratedType type)
    {
        var useLong = type.Values.Any(v => v.Value < int.MinValue || v.Value > int.MaxValue);
        sb.Append("public enum ").Append(typeName);
        if (useLong)
        {
            sb.Append(" : long");
        }

        sb.AppendLine();
        sb.AppendLine("{");
        for (var i = 0; i < type.Values.Count; i++)
        {
            var named = type.Values[i];
            var member = SanitizeIdentifier(named.Name);
            if (Keywords.Contains(member))
            {
                member += "Value";
            }

            var literal = named.Value.ToString(CultureInfo.InvariantCulture);
            if (useLong && (named.Value < int.MinValue || named.Value > int.MaxValue))
            {
                literal += "L";
            }

            sb.AppendLine(
                $"    /// <summary>ASN.1 enumerated {named.Name}({named.Value.ToString(CultureInfo.InvariantCulture)}).</summary>");
            sb.Append($"    {member} = {literal}");
            sb.AppendLine(i + 1 < type.Values.Count ? "," : "");
        }

        sb.AppendLine("}");
    }

    private void EmitNamedIntegerConstants(StringBuilder sb, string typeName, IntegerType type)
    {
        var namedValues = type.NamedValues
            ?? throw new InvalidOperationException($"INTEGER '{typeName}' has no namedValues.");
        var useLong = namedValues.Any(v => v.Value < int.MinValue || v.Value > int.MaxValue);
        sb.AppendLine($"public static class {typeName}");
        sb.AppendLine("{");
        foreach (var named in namedValues)
        {
            var member = SanitizeIdentifier(named.Name);
            if (Keywords.Contains(member))
            {
                member += "Value";
            }

            var literal = named.Value.ToString(CultureInfo.InvariantCulture);
            if (useLong)
            {
                literal += "L";
            }

            var constType = useLong ? "long" : "int";
            sb.AppendLine(
                $"    /// <summary>ASN.1 named integer {named.Name}({named.Value.ToString(CultureInfo.InvariantCulture)}).</summary>");
            sb.AppendLine($"    public const {constType} {member} = {literal};");
        }

        sb.AppendLine("}");
    }

    private void EmitStructConstructor(StringBuilder sb, IrDocument document, IrModule module,
        string owner, IReadOnlyList<IrComponent> fields)
    {
        sb.AppendLine();
        sb.AppendLine($"    public {owner}()");
        sb.AppendLine("    {");
        foreach (var field in fields)
        {
            var optional = (field.Optional || field.ExtensionAddition == true) && field.Default is null;
            if (field.Default is null && Initializer(document, module, owner, field.Name,
                    field.Type, optional, field.Options).Length == 0)
                sb.AppendLine($"        {PropertyName(field, owner)} = default!;");
        }
        sb.AppendLine("    }");
    }

    private void EmitProperty(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string typeName,
        IrComponent field,
        bool optional,
        bool privateSetter)
    {
        var prop = PropertyName(field, typeName);
        EmitCollapsedAliasDoc(sb, document, module, field.Type);
        var csType = CsType(document, module, typeName, field.Name, field.Type, optional, field.Options);
        var setter = privateSetter ? "private set" : "set";
        var initializer = privateSetter
            ? ""
            : field.Default is not null
                ? " = " + DefaultValueExpression(document, module, typeName, field) + ";"
                : Initializer(document, module, typeName, field.Name, field.Type, optional, field.Options);
        sb.AppendLine($"    public {csType} {prop} {{ get; {setter}; }}{initializer}");
    }

    private void EmitCachedDefaults(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        IReadOnlyList<IrComponent> components)
    {
        foreach (var field in components.Where(NeedsCachedDefault))
        {
            var (_, target) = ResolveDefaultTarget(document, module, field.Type);
            var storageType = target is BitStringType ? "Asn1BitString" : "Asn1Oid";
            sb.AppendLine(
                $"    private static readonly {storageType} {DefaultFieldName(field)} = " +
                $"{DefaultStorageExpression(document, module, owner, field)};");
        }

        if (components.Any(NeedsCachedDefault))
        {
            sb.AppendLine();
        }
    }

    private static bool NeedsCachedDefault(IrComponent field) =>
        field.Default is IrOidValue or IrBitStringValue;

    private static string DefaultFieldName(IrComponent field) =>
        "s_default" + SanitizeIdentifier(field.Name);

    private string DefaultValueExpression(
        IrDocument document,
        IrModule module,
        string owner,
        IrComponent field)
    {
        var (_, target) = ResolveDefaultTarget(document, module, field.Type);
        if (target is BitStringType { NamedBits.Count: > 0 })
        {
            var csType = CsType(document, module, owner, field.Name, field.Type, optional: false, field.Options);
            return $"new {csType} {{ Value = {DefaultFieldName(field)} }}";
        }

        return NeedsCachedDefault(field)
            ? DefaultFieldName(field)
            : DefaultStorageExpression(document, module, owner, field);
    }

    private string DefaultNotEqualExpression(
        IrDocument document,
        IrModule module,
        string owner,
        IrComponent field,
        string valueExpression)
    {
        if (field.Default is IrStructuredValue or IrCollectionValue or IrChoiceValue or IrTypedValue or IrOctetStringValue)
            return "!(" + ValueEqualsExpression(document, module, owner, field.Name, field.Type, field.Default, valueExpression) + ")";
        var (_, target) = ResolveDefaultTarget(document, module, field.Type);
        var value = target is BitStringType { NamedBits.Count: > 0 }
            ? valueExpression + ".Value"
            : valueExpression;
        var defaultValue = NeedsCachedDefault(field)
            ? DefaultFieldName(field)
            : DefaultStorageExpression(document, module, owner, field);
        return $"{value} != {defaultValue}";
    }

    private string DefaultStorageExpression(
        IrDocument document,
        IrModule module,
        string owner,
        IrComponent field)
    {
        if (field.Default is IrStructuredValue or IrCollectionValue or IrChoiceValue or IrTypedValue or IrOctetStringValue)
            return ValueExpression(document, module, owner, field.Name, field.Type, field.Default);
        var (_, target) = ResolveDefaultTarget(document, module, field.Type);
        return (target, field.Default) switch
        {
            (BooleanType, IrBooleanValue value) => value.Value ? "true" : "false",
            (NullType, IrNullValue) => "Asn1Null.Value",
            (OidType, IrOidValue value) => KnownOidExpression(document, module, value.Value)
                ?? $"Asn1Oid.Parse(\"{EscapeCSharpString(value.Value)}\")",
            (StringType, IrStringValue value) => $"\"{EscapeCSharpString(value.Value)}\"",
            (BitStringType, IrBitStringValue value) => BitStringDefaultExpression(value),
            (EnumeratedType, IrIntegerValue value) =>
                $"({CsType(document, module, owner, field.Name, field.Type, optional: false, field.Options)})" +
                IntegerLiteral(value.Value, "long"),
            (IntegerType, IrIntegerValue value) => IntegerDefaultExpression(
                value.Value,
                TryResolveIntegerRepresentation(document, module, field.Type)
                    ?? IrOptions.IntegerRepresentations.Der),
            _ => throw new NotSupportedException(
                $"DEFAULT kind '{field.Default?.Kind ?? "null"}' is not supported for " +
                $"ASN.1 type '{target.Kind}' on '{owner}.{field.Name}'.")
        };
    }

    private static (IrModule Module, TypeExpr Type) ResolveDefaultTarget(
        IrDocument document,
        IrModule module,
        TypeExpr type)
    {
        var visited = new HashSet<string>(StringComparer.Ordinal);
        while (type is RefType reference)
        {
            var key = (reference.Module ?? module.Name) + "::" + reference.Name;
            if (!visited.Add(key))
            {
                throw new NotSupportedException($"Circular type alias '{reference.Name}'.");
            }

            var found = FindWithModule(document, module, reference)
                ?? throw new NotSupportedException($"Cannot resolve DEFAULT type reference '{reference.Name}'.");
            module = found.Module;
            type = found.Def.Type;
        }

        return (module, type);
    }

    private static string IntegerDefaultExpression(long value, string representation) => representation switch
    {
        IrOptions.IntegerRepresentations.Int32 when value is >= int.MinValue and <= int.MaxValue =>
            IntegerLiteral(value, "int"),
        IrOptions.IntegerRepresentations.UInt32 when value is >= uint.MinValue and <= uint.MaxValue =>
            IntegerLiteral(value, "uint"),
        IrOptions.IntegerRepresentations.Int64 => IntegerLiteral(value, "long"),
        IrOptions.IntegerRepresentations.UInt64 when value >= 0 => IntegerLiteral(value, "ulong"),
        IrOptions.IntegerRepresentations.BigInt =>
            $"BigInteger.Parse(\"{value.ToString(CultureInfo.InvariantCulture)}\", CultureInfo.InvariantCulture)",
        IrOptions.IntegerRepresentations.Der =>
            $"Asn1Integer.FromInt64({IntegerLiteral(value, "long")})",
        _ => throw new NotSupportedException(
            $"INTEGER DEFAULT '{value.ToString(CultureInfo.InvariantCulture)}' does not fit representation '{representation}'.")
    };

    private static string IntegerLiteral(long value, string representation)
    {
        var text = value.ToString(CultureInfo.InvariantCulture);
        return representation switch
        {
            "int" => text,
            "uint" => text + "U",
            "long" when value == long.MinValue => "(-9223372036854775807L - 1L)",
            "long" => text + "L",
            "ulong" => text + "UL",
            _ => throw new ArgumentOutOfRangeException(nameof(representation))
        };
    }

    private static string BitStringDefaultExpression(IrBitStringValue value)
    {
        string bits;
        if (value.Bits is not null)
        {
            bits = value.Bits;
        }
        else if (value.Hex is not null)
        {
            bits = string.Concat(value.Hex.Select(c => Convert.ToString(Convert.ToInt32(c.ToString(), 16), 2).PadLeft(4, '0')));
        }
        else
        {
            throw new NotSupportedException("BIT STRING DEFAULT requires bits or hex.");
        }

        if (bits.Any(c => c is not ('0' or '1')))
        {
            throw new NotSupportedException("BIT STRING DEFAULT contains a character other than '0' or '1'.");
        }

        if (bits.Length == 0)
        {
            return "default";
        }

        var bytes = new byte[(bits.Length + 7) / 8];
        for (var i = 0; i < bits.Length; i++)
        {
            if (bits[i] == '1')
            {
                bytes[i / 8] |= (byte)(1 << (7 - i % 8));
            }
        }

        var byteLiteral = string.Join(", ", bytes.Select(b => $"0x{b:X2}"));
        return $"Asn1BitString.CopyFrom(new byte[] {{ {byteLiteral} }}, {bytes.Length * 8 - bits.Length})";
    }

    private void EmitCollapsedAliasDoc(StringBuilder sb, IrDocument document, IrModule module, TypeExpr type)
    {
        if (type is not RefType reference)
        {
            return;
        }

        var found = Find(document, module, reference);
        if (found is null || !IsCollapsibleAlias(found.Type))
        {
            return;
        }

        sb.AppendLine($"    /// <summary>ASN.1 alias {reference.Name} ::= {FormatAliasRhs(document, module, found.Type)}.</summary>");
    }

    private string FormatAliasRhs(IrDocument document, IrModule module, TypeExpr type) => type switch
    {
        BooleanType => "BOOLEAN",
        IntegerType => "INTEGER",
        EnumeratedType => "ENUMERATED",
        BitStringType => "BIT STRING",
        OctetStringType => "OCTET STRING",
        NullType => "NULL",
        OidType => "OBJECT IDENTIFIER",
        StringType stringType => stringType.Form switch
        {
            StringTypes.Utf8 => "UTF8String",
            StringTypes.Numeric => "NumericString",
            StringTypes.Printable => "PrintableString",
            StringTypes.Teletex => "TeletexString",
            StringTypes.T61 => "T61String",
            StringTypes.Videotex => "VideotexString",
            StringTypes.Ia5 => "IA5String",
            StringTypes.Graphic => "GraphicString",
            StringTypes.Visible => "VisibleString",
            StringTypes.General => "GeneralString",
            StringTypes.Universal => "UniversalString",
            StringTypes.Bmp => "BMPString",
            _ => "String"
        },
        TimeType timeType => timeType.Form == TimeTypes.Utc ? "UTCTime" : "GeneralizedTime",
        AnyType => "ANY",
        RefType reference => reference.Name,
        SequenceType => "SEQUENCE",
        SetType => "SET",
        ChoiceType choice when IsSingleAlternativeChoice(choice) =>
            "CHOICE { " + choice.Components[0].Name + " "
            + FormatAliasRhs(document, module, choice.Components[0].Type) + " }",
        ChoiceType => "CHOICE",
        SequenceOfType sequenceOf => "SEQUENCE OF " + FormatAliasRhs(document, module, sequenceOf.Element),
        SetOfType setOf => "SET OF " + FormatAliasRhs(document, module, setOf.Element),
        _ => type.Kind
    };

    private static void EmitDefaultTag(StringBuilder sb, TypeExpr type, bool constructed, string fallback)
    {
        var tag = type.Tag is null ? fallback : TagFromIr(type.Tag, constructed || type.Tag.Mode == TagModes.Explicit);
        sb.AppendLine();
        sb.AppendLine($"    public static Asn1Tag DefaultTag {{ get; }} = {tag};");
    }

    private void EmitEncodeField(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        IrComponent field,
        string indent,
        string writer)
    {
        EmitEncodeFieldFromExpr(
            sb,
            document,
            module,
            owner,
            field,
            indent,
            writer,
            PropertyName(field, owner));
    }

    private void EmitEncodeFieldFromExpr(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        IrComponent field,
        string indent,
        string writer,
        string expr)
    {
        if (field.Default is not null)
        {
            sb.AppendLine($"{indent}if ({DefaultNotEqualExpression(document, module, owner, field, expr)})");
            sb.AppendLine($"{indent}{{");
            EmitEncodeValue(
                sb,
                document,
                module,
                owner,
                field.Name,
                field.Type,
                indent + "    ",
                writer,
                expr,
                fieldOptions: field.Options);
            sb.AppendLine($"{indent}}}");
        }
        else if (field.Optional || field.ExtensionAddition == true)
        {
            sb.AppendLine($"{indent}if ({expr} != null)");
            sb.AppendLine($"{indent}{{");
            EmitEncodeValue(
                sb,
                document,
                module,
                owner,
                field.Name,
                field.Type,
                indent + "    ",
                writer,
                UnwrapOptional(document, module, field.Type, expr, field.Options),
                fieldOptions: field.Options);
            sb.AppendLine($"{indent}}}");
        }
        else
        {
            EmitEncodeValue(
                sb,
                document,
                module,
                owner,
                field.Name,
                field.Type,
                indent,
                writer,
                expr,
                fieldOptions: field.Options);
        }
    }

    private string UnwrapOptional(
        IrDocument document,
        IrModule module,
        TypeExpr type,
        string expr,
        JsonObject? fieldOptions = null)
    {
        return IsValueOptionalWrapper(document, module, type)
            || ShouldEmitRetainEncoded(document, module, type, fieldOptions)
                ? expr + ".Value"
                : expr;
    }

    private bool IsValueOptionalWrapper(IrDocument document, IrModule module, TypeExpr type)
    {
        var unwrapped = UnwrapAliases(document, module, type);
        if (IsEnumeratedRefOrType(document, module, unwrapped))
        {
            return true;
        }

        return ResolvePrimitive(unwrapped) is TypeKinds.Boolean or TypeKinds.Integer or TypeKinds.Null
            or TypeKinds.OctetString or TypeKinds.BitString or TypeKinds.Time or TypeKinds.Any
            or TypeKinds.Oid;
    }

    private bool IsEnumeratedRefOrType(IrDocument document, IrModule module, TypeExpr type) =>
        type is EnumeratedType ||
        (type is RefType reference && Find(document, module, reference)?.Type is EnumeratedType);

    private void EmitEncodeValue(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        string indent,
        string writer,
        string expr,
        string? forceTag = null,
        bool encodeLazyWrapper = true,
        JsonObject? fieldOptions = null,
        IrModule? emittingModule = null)
    {
        emittingModule ??= module;
        if (encodeLazyWrapper && ShouldEmitLazy(document, module, type, fieldOptions))
        {
            sb.AppendLine($"{indent}if ({expr}.HasEncoded)");
            sb.AppendLine($"{indent}{{");
            sb.AppendLine($"{indent}    {writer}.WriteRaw({expr}.EncodedMemory.Span);");
            sb.AppendLine($"{indent}}}");
            sb.AppendLine($"{indent}else");
            sb.AppendLine($"{indent}{{");
            EmitEncodeValue(
                sb,
                document,
                module,
                owner,
                hint,
                type,
                indent + "    ",
                writer,
                $"{expr}.Value",
                forceTag,
                encodeLazyWrapper: false,
                fieldOptions: null,
                emittingModule: emittingModule);
            sb.AppendLine($"{indent}}}");
            return;
        }

        if (encodeLazyWrapper && ShouldEmitRetainEncoded(document, module, type, fieldOptions))
        {
            EmitEncodeValue(
                sb,
                document,
                module,
                owner,
                hint,
                type,
                indent,
                writer,
                $"{expr}.Value",
                forceTag,
                encodeLazyWrapper: false,
                fieldOptions: null,
                emittingModule: emittingModule);
            return;
        }

        var original = type;
        var resolvedModule = module;
        type = UnwrapAliases(document, ref resolvedModule, type);

        if (type.Tag?.Mode == TagModes.Explicit && forceTag is null)
        {
            sb.AppendLine($"{indent}using ({writer}.EnterExplicit({TagFromIr(type.Tag, constructed: true)}))");
            sb.AppendLine($"{indent}{{");
            var inner = CloneUntagged(type);
            if (inner is SequenceOfType or SetOfType)
            {
                EmitOfEncode(
                    sb,
                    document,
                    resolvedModule,
                    original,
                    owner,
                    hint,
                    inner,
                    indent + "    ",
                    writer,
                    expr,
                    forceTag: null,
                    emittingModule);
            }
            else
            {
                EmitEncodeValue(
                    sb,
                    document,
                    resolvedModule,
                    owner,
                    hint,
                    inner,
                    indent + "    ",
                    writer,
                    expr,
                    encodeLazyWrapper: false,
                    emittingModule: emittingModule);
            }

            sb.AppendLine($"{indent}}}");
            return;
        }

        if (type is SequenceOfType or SetOfType)
        {
            EmitOfEncode(
                sb,
                document,
                resolvedModule,
                original,
                owner,
                hint,
                type,
                indent,
                writer,
                expr,
                forceTag,
                emittingModule);
            return;
        }

        if (ContainedType(type) is { } content)
        {
            ContainedNaming(document, module, original, owner, hint, out var contentModule, out var contentOwner, out var contentHint);
            sb.AppendLine($"{indent}{writer}.WriteContained({forceTag ?? TagExpr(document, module, type)}, {BoolLiteral(type is BitStringType)}, {expr}, static (inner, value) =>");
            sb.AppendLine($"{indent}{{");
            EmitEncodeValue(sb, document, contentModule, contentOwner, contentHint, content, indent + "    ", "inner", "value");
            sb.AppendLine($"{indent}}});");
            return;
        }

        if (type is AnyType)
        {
            if (forceTag is not null || type.Tag is not null)
            {
                var anyTag = forceTag ?? TagExpr(document, module, type);
                sb.AppendLine($"{indent}{writer}.WriteAny({anyTag}, {expr});");
            }
            else
            {
                sb.AppendLine($"{indent}{writer}.WriteAny({expr});");
            }

            return;
        }

        var encodeTag = forceTag ?? TagExpr(document, module, type);
        if (IsEnumeratedRefOrType(document, module, type))
        {
            sb.AppendLine($"{indent}{writer}.WriteEnumerated({encodeTag}, (BigInteger)(long){expr});");
            return;
        }

        var primitive = ResolvePrimitive(type);
        if (primitive is not null)
        {
            sb.AppendLine($"{indent}{WriteCall(writer, encodeTag, expr, type)};");
            return;
        }

        if (type is RefType reference)
        {
            var resolved = Find(document, module, reference);
            if (resolved?.Type is ChoiceType or AnyType)
            {
                sb.AppendLine($"{indent}{expr}.Encode({writer});");
                return;
            }
        }

        if (type is ChoiceType)
        {
            sb.AppendLine($"{indent}{expr}.Encode({writer});");
            return;
        }

        sb.AppendLine($"{indent}{expr}.Encode({writer}, {encodeTag});");
    }

    private void EmitOfEncode(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        TypeExpr original,
        string owner,
        string hint,
        TypeExpr ofType,
        string indent,
        string writer,
        string expr,
        string? forceTag,
        IrModule? emittingModule = null)
    {
        emittingModule ??= module;
        ResolveOfItemNaming(
            document,
            module,
            original,
            owner,
            hint,
            out var itemOwner,
            out var itemHint,
            emittingModule);
        var writeMethod = ofType is SetOfType ? "WriteSetOf" : "WriteSequenceOf";
        var tag = forceTag ?? TagExpr(document, module, ofType);
        var element = ofType is SetOfType setOf ? setOf.Element : ((SequenceOfType)ofType).Element;
        sb.AppendLine($"{indent}{writer}.{writeMethod}({tag}, {expr}, static (inner, item) =>");
        sb.AppendLine($"{indent}{{");
        EmitEncodeValue(
            sb,
            document,
            module,
            itemOwner,
            itemHint,
            element,
            indent + "    ",
            "inner",
            "item",
            fieldOptions: element.Options,
            emittingModule: emittingModule);
        sb.AppendLine($"{indent}}});");
    }

    private void EmitDecodeField(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        IrComponent field,
        IReadOnlyList<IrComponent> ownerComponents,
        string indent,
        string reader,
        string target)
    {
        var prop = PropertyName(field, owner);
        if (field.Optional || field.ExtensionAddition == true || field.Default is not null)
        {
            if (IsUntaggedAny(document, module, field.Type))
            {
                sb.AppendLine($"{indent}if (!{reader}.Eof)");
                sb.AppendLine($"{indent}{{");
                EmitDecodeAssign(
                    sb,
                    document,
                    module,
                    owner,
                    field.Name,
                    field.Type,
                    ownerComponents,
                    indent + "    ",
                    reader,
                    $"{target}.{prop}",
                    targetObject: target,
                    fieldOptions: field.Options);
                sb.AppendLine($"{indent}}}");
            }
            else
            {
                var peekTag = "tag_" + SanitizeIdentifier(field.Name);
                sb.AppendLine(
                    $"{indent}if ({reader}.TryPeekTag(out var {peekTag}) && {PeekMatchExpr(document, module, field.Type, peekTag)})");
                sb.AppendLine($"{indent}{{");
                EmitDecodeAssign(
                    sb,
                    document,
                    module,
                    owner,
                    field.Name,
                    field.Type,
                    ownerComponents,
                    indent + "    ",
                    reader,
                    $"{target}.{prop}",
                    targetObject: target,
                    fieldOptions: field.Options);
                sb.AppendLine($"{indent}}}");
            }
        }
        else
        {
            EmitDecodeAssign(
                sb,
                document,
                module,
                owner,
                field.Name,
                field.Type,
                ownerComponents,
                indent,
                reader,
                $"{target}.{prop}",
                targetObject: target,
                fieldOptions: field.Options);
        }
    }

    /// <summary>
    /// Optional SEQUENCE/SET fields peek a single universal tag; untagged multi-alternative CHOICE
    /// (including named refs like Time) must match any alternative tag, not Sequence.
    /// </summary>
    private string PeekMatchExpr(IrDocument document, IrModule module, TypeExpr type, string peekedVar)
    {
        if (TryGetUntaggedMultiAltChoice(document, module, type, out var choice))
        {
            var alts = choice.Components
                .Select(c => $"{peekedVar}.MatchesIgnoreConstructed({TagExpr(document, module, c.Type)})");
            return "(" + string.Join(" || ", alts) + ")";
        }

        return $"{peekedVar}.MatchesIgnoreConstructed({TagExpr(document, module, type)})";
    }

    private bool TryGetUntaggedMultiAltChoice(
        IrDocument document,
        IrModule module,
        TypeExpr type,
        out ChoiceType choice)
    {
        choice = null!;
        if (type.Tag is not null)
        {
            return false;
        }

        var cursor = UnwrapAliases(document, module, type);
        if (cursor.Tag is not null)
        {
            return false;
        }

        if (cursor is RefType reference)
        {
            var found = Find(document, module, reference);
            if (found?.Type is ChoiceType named &&
                !IsSingleAlternativeChoice(named) &&
                named.Tag is null)
            {
                choice = named;
                return true;
            }

            return false;
        }

        if (cursor is ChoiceType inline &&
            !IsSingleAlternativeChoice(inline) &&
            inline.Tag is null)
        {
            choice = inline;
            return true;
        }

        return false;
    }

    private bool IsUntaggedAny(IrDocument document, IrModule module, TypeExpr type)
    {
        if (type.Tag is not null)
        {
            return false;
        }

        var unwrapped = UnwrapAliases(document, module, type);
        return unwrapped is AnyType { Tag: null };
    }

    private void EmitDecodeAssign(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        IReadOnlyList<IrComponent>? ownerComponents,
        string indent,
        string reader,
        string target,
        string? forceTag = null,
        string? targetObject = null,
        JsonObject? fieldOptions = null)
    {
        string? openKey = null;

        if (ShouldEmitLazy(document, module, type, fieldOptions))
        {
            EmitDeferredDecodeAssign(
                sb,
                document,
                module,
                owner,
                hint,
                type,
                ownerComponents,
                indent,
                reader,
                target,
                forceTag,
                targetObject,
                openKey,
                method: "ReadLazy");
            return;
        }

        if (ShouldEmitRetainEncoded(document, module, type, fieldOptions))
        {
            EmitDeferredDecodeAssign(
                sb,
                document,
                module,
                owner,
                hint,
                type,
                ownerComponents,
                indent,
                reader,
                target,
                forceTag,
                targetObject,
                openKey,
                method: "ReadWithOriginalEncoding");
            return;
        }

        EmitDecodeAssignBody(
            sb,
            document,
            module,
            owner,
            hint,
            type,
            ownerComponents,
            indent,
            reader,
            target,
            forceTag,
            targetObject,
            openKey,
            fieldOptions);
    }

    private void EmitDeferredDecodeAssign(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        IReadOnlyList<IrComponent>? ownerComponents,
        string indent,
        string reader,
        string target,
        string? forceTag,
        string? targetObject,
        string? openKey,
        string method)
    {
        sb.AppendLine($"{indent}{target} = {reader}.{method}(r =>");
        sb.AppendLine($"{indent}{{");
        EmitDecodeReturn(
            sb,
            document,
            module,
            owner,
            hint,
            type,
            ownerComponents,
            indent + "    ",
            "r",
            forceTag,
            targetObject,
            openKey,
            fieldOptions: null);
        sb.AppendLine($"{indent}}});");
    }

    private void EmitDecodeReturn(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        IReadOnlyList<IrComponent>? ownerComponents,
        string indent,
        string reader,
        string? forceTag,
        string? targetObject,
        string? openKey,
        JsonObject? fieldOptions,
        TypeExpr? originalForOf = null)
    {
        var original = originalForOf ?? type;
        var unwrapped = UnwrapAliases(document, module, type);
        if (unwrapped.Tag?.Mode == TagModes.Explicit && forceTag is null)
        {
            var explicitTag = TagFromIr(unwrapped.Tag, constructed: true);
            sb.AppendLine($"{indent}using ({reader}.EnterExplicit({explicitTag}))");
            sb.AppendLine($"{indent}{{");
            sb.Append($"{indent}    var decodedValue = ");
            EmitDecodeExpr(
                sb,
                document,
                module,
                owner,
                hint,
                CloneUntagged(unwrapped),
                reader,
                forceTag: null,
                openTypeKeyExpr: openKey,
                allowLazy: false,
                fieldOptions: fieldOptions,
                originalForOf: original);
            sb.AppendLine(";");
            sb.AppendLine($"{indent}    {reader}.ThrowIfNotEmpty();");
            sb.AppendLine($"{indent}    return decodedValue;");
            sb.AppendLine($"{indent}}}");
            return;
        }

        sb.Append($"{indent}return ");
        EmitDecodeExpr(
            sb,
            document,
            module,
            owner,
            hint,
            type,
            reader,
            forceTag,
            openKey,
            allowLazy: false,
            fieldOptions);
        sb.AppendLine(";");
    }

    private void EmitDecodeAssignBody(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        IReadOnlyList<IrComponent>? ownerComponents,
        string indent,
        string reader,
        string target,
        string? forceTag,
        string? targetObject,
        string? openKey,
        JsonObject? fieldOptions,
        TypeExpr? originalForOf = null)
    {
        var original = originalForOf ?? type;
        var unwrapped = UnwrapAliases(document, module, type);
        if (unwrapped.Tag?.Mode == TagModes.Explicit && forceTag is null)
        {
            var explicitTag = TagFromIr(unwrapped.Tag, constructed: true);
            sb.AppendLine($"{indent}using ({reader}.EnterExplicit({explicitTag}))");
            sb.AppendLine($"{indent}{{");
            EmitDecodeAssignBody(
                sb,
                document,
                module,
                owner,
                hint,
                CloneUntagged(unwrapped),
                ownerComponents,
                indent + "    ",
                reader,
                target,
                forceTag: null,
                targetObject,
                openKey,
                fieldOptions,
                originalForOf: original);
            sb.AppendLine($"{indent}    {reader}.ThrowIfNotEmpty();");
            sb.AppendLine($"{indent}}}");
            return;
        }

        sb.Append(indent);
        sb.Append(target);
        sb.Append(" = ");
        EmitDecodeExpr(
            sb,
            document,
            module,
            owner,
            hint,
            type,
            reader,
            forceTag,
            openKey,
            allowLazy: false,
            fieldOptions,
            originalForOf: original);
        sb.AppendLine(";");
    }

    private void EmitDecodeExpr(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        string reader,
        string? forceTag = null,
        string? openTypeKeyExpr = null,
        bool allowLazy = true,
        JsonObject? fieldOptions = null,
        TypeExpr? originalForOf = null,
        IrModule? emittingModule = null)
    {
        emittingModule ??= module;
        if (allowLazy && ShouldEmitLazy(document, module, type, fieldOptions))
        {
            sb.Append($"{reader}.ReadLazy(r => ");
            EmitDecodeExpr(
                sb,
                document,
                module,
                owner,
                hint,
                type,
                "r",
                forceTag,
                openTypeKeyExpr,
                allowLazy: false,
                fieldOptions: null,
                emittingModule: emittingModule);
            sb.Append(')');
            return;
        }

        if (allowLazy && ShouldEmitRetainEncoded(document, module, type, fieldOptions))
        {
            sb.Append($"{reader}.ReadWithOriginalEncoding(r => ");
            EmitDecodeExpr(
                sb,
                document,
                module,
                owner,
                hint,
                type,
                "r",
                forceTag,
                openTypeKeyExpr,
                allowLazy: false,
                fieldOptions: null,
                emittingModule: emittingModule);
            sb.Append(')');
            return;
        }

        var integerRepresentation = TryResolveIntegerRepresentation(document, module, type);
        var original = originalForOf ?? type;
        var resolvedModule = module;
        type = UnwrapAliases(document, ref resolvedModule, type);

        if (type.Tag?.Mode == TagModes.Explicit && forceTag is null)
        {
            throw new InvalidOperationException(
                $"EXPLICIT decode for '{owner}.{hint}' must use EnterExplicit (statement form).");
        }

        if (type is SequenceOfType or SetOfType)
        {
            EmitOfDecodeExpr(
                sb,
                document,
                resolvedModule,
                original,
                owner,
                hint,
                type,
                reader,
                forceTag,
                openTypeKeyExpr,
                emittingModule);
            return;
        }

        if (ContainedType(type) is { } content)
        {
            ContainedNaming(document, resolvedModule, original, owner, hint, out var contentModule, out var contentOwner, out var contentHint);
            var known = content is AnyType ? "false" : "true";
            sb.Append($"{reader}.ReadContained({forceTag ?? TagExpr(document, module, type)}, {BoolLiteral(type is BitStringType)}, {known}, {openTypeKeyExpr ?? "0"}, static (inner, key) => ");
            EmitDecodeExpr(
                sb,
                document,
                contentModule,
                contentOwner,
                contentHint,
                content,
                "inner",
                openTypeKeyExpr: "key",
                emittingModule: emittingModule);
            sb.Append(')');
            return;
        }

        if (type is AnyType)
        {
            if (forceTag is not null || type.Tag is not null)
            {
                var anyTag = forceTag ?? TagExpr(document, module, type);
                sb.Append($"{reader}.ReadAny({anyTag})");
            }
            else
            {
                sb.Append($"{reader}.ReadAny()");
            }

            return;
        }

        var decodeTag = forceTag ?? TagExpr(document, resolvedModule, type);
        if (IsEnumeratedRefOrType(document, resolvedModule, type))
        {
            var enumName = NamedTypeName(document, resolvedModule, owner, hint, type, emittingModule);
            sb.Append($"({enumName})(long){reader}.ReadEnumerated({decodeTag})");
            return;
        }

        var primitive = ResolvePrimitive(type);
        if (primitive is not null)
        {
            sb.Append(ReadCall(reader, decodeTag, type, integerRepresentation));
            return;
        }

        var typeName = NamedTypeName(document, resolvedModule, owner, hint, type, emittingModule);
        var contextSuffix = ContextSuffix(typeName);
        // Qualify same-module names so Decode calls do not bind to a same-named property on the owner.
        if (!typeName.Contains('.', StringComparison.Ordinal))
        {
            typeName = ModuleNamespace(emittingModule) + "." + typeName;
        }

        if (type is ChoiceType ||
            (type is RefType r && Find(document, resolvedModule, r)?.Type is ChoiceType or AnyType))
        {
            sb.Append($"{typeName}.Decode({reader}{contextSuffix})");
            return;
        }

        sb.Append($"{typeName}.Decode({reader}, {decodeTag}{contextSuffix})");
    }

    private IEnumerable<(string? Name, TypeExpr Type, JsonObject? Options)> ExpandOpenTypeChoice(
        IrDocument document,
        IrModule targetModule,
        IrModule sourceModule,
        string? name,
        TypeExpr type,
        JsonObject? options,
        HashSet<ChoiceType> path)
    {
        var resolved = type;
        var context = sourceModule;
        var aliases = new HashSet<string>(StringComparer.Ordinal);
        while (resolved is RefType reference && resolved.Tag is null)
        {
            var found = FindWithModule(document, context, reference);
            if (found is null || !aliases.Add(found.Value.Module.Name + "::" + reference.Name)) break;
            context = found.Value.Module;
            resolved = found.Value.Def.Type;
        }

        if (resolved is ChoiceType { Tag: not null } taggedChoice && type.Tag is null)
        {
            // Named CHOICE codecs operate on their alternatives; retain the typedef's outer wrapper here.
            type = CloneType(type);
            type.Tag = taggedChoice.Tag;
        }

        if (resolved is ChoiceType { Tag: null, Extensible: false } choice && type.Tag is null && path.Add(choice))
        {
            foreach (var component in choice.Components)
            {
                var componentName = IrOptions.CSharpPropertyName(component.Options) ?? component.Name;
                var flattenedName = name is null ? componentName : name + "_" + componentName;
                foreach (var leaf in ExpandOpenTypeChoice(document, targetModule, context, flattenedName, component.Type, component.Options, path))
                    yield return leaf;
            }
            path.Remove(choice);
            yield break;
        }

        yield return (name, QualifyOpenTypeReferences(document, sourceModule, targetModule, type), options);
    }

    private static TypeExpr QualifyOpenTypeReferences(
        IrDocument document, IrModule sourceModule, IrModule targetModule, TypeExpr type)
    {
        if (sourceModule == targetModule) return type;
        var node = JsonSerializer.SerializeToNode(type, IrSerializer.JsonOptions)!;
        void Qualify(JsonNode? current)
        {
            if (current is JsonObject obj)
            {
                if (obj["kind"]?.GetValue<string>() == TypeKinds.Ref)
                {
                    var reference = obj.Deserialize<TypeExpr>(IrSerializer.JsonOptions) as RefType;
                    var found = FindWithModule(document, sourceModule, reference!);
                    if (found is not null) obj["module"] = found.Value.Module.Name;
                }
                // Visit only type expressions; arbitrary options may contain objects named "ref".
                if (obj["element"] is { } element) Qualify(element);
                if (obj["containing"] is { } containing) Qualify(containing);
                foreach (var collection in new[] { "components", "bindings" })
                {
                    if (obj[collection] is JsonArray array)
                    {
                        foreach (var child in array) Qualify(child?["type"]);
                    }
                }
            }
        }
        Qualify(node);
        return node.Deserialize<TypeExpr>(IrSerializer.JsonOptions)!;
    }

    private static string EscapeCSharpString(string value)
    {
        var escaped = new StringBuilder(value.Length);
        foreach (var c in value)
        {
            switch (c)
            {
                case '\\': escaped.Append("\\\\"); break;
                case '"': escaped.Append("\\\""); break;
                case '\0': escaped.Append("\\0"); break;
                case '\a': escaped.Append("\\a"); break;
                case '\b': escaped.Append("\\b"); break;
                case '\f': escaped.Append("\\f"); break;
                case '\n': escaped.Append("\\n"); break;
                case '\r': escaped.Append("\\r"); break;
                case '\t': escaped.Append("\\t"); break;
                case '\v': escaped.Append("\\v"); break;
                default:
                    if (char.IsControl(c))
                    {
                        escaped.Append("\\u").Append(((int)c).ToString("X4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        escaped.Append(c);
                    }

                    break;
            }
        }

        return escaped.ToString();
    }

    private void EmitOfDecodeExpr(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        TypeExpr original,
        string owner,
        string hint,
        TypeExpr ofType,
        string reader,
        string? forceTag,
        string? openTypeKeyExpr,
        IrModule? emittingModule = null)
    {
        emittingModule ??= module;
        ResolveOfItemNaming(
            document,
            module,
            original,
            owner,
            hint,
            out var itemOwner,
            out var itemHint,
            emittingModule);
        var ofElement = ofType is SetOfType collection ? collection.Element : ((SequenceOfType)ofType).Element;
        var elementLookup = module;
        var elementUnwrappedForName = UnwrapAliases(document, ref elementLookup, ofElement);
        var elementName = NamedTypeName(
            document,
            elementLookup,
            itemOwner,
            itemHint,
            elementUnwrappedForName,
            emittingModule);
        var context = ChildContext(elementName);
        var previousContext = _callbackContext;
        var key = openTypeKeyExpr;
        if (context.Count > 0)
        {
            key = context.Count == 1 ? context[0] : "(" + string.Join(", ", context) + ")";
            _callbackContext = Enumerable.Range(0, context.Count).Select(i => context.Count == 1 ? "key" : "key.Item" + (i + 1)).ToArray();
        }
        try
        {
            EmitOfDecodeCore(
                sb,
                document,
                module,
                itemOwner,
                itemHint,
                ofType,
                reader,
                forceTag,
                key,
                emittingModule);
        }
        finally { _callbackContext = previousContext; }
    }

    private void EmitOfDecodeCore(
        StringBuilder sb,
        IrDocument document,
        IrModule module,
        string itemOwner,
        string itemHint,
        TypeExpr ofType,
        string reader,
        string? forceTag,
        string? openTypeKeyExpr,
        IrModule emittingModule)
    {
        var readMethod = ofType is SetOfType ? "ReadSetOf" : "ReadSequenceOf";
        var tag = forceTag ?? TagExpr(document, module, ofType);
        var element = ofType is SetOfType setOf ? setOf.Element : ((SequenceOfType)ofType).Element;
        var elementUnwrapped = UnwrapAliases(document, module, element);
        if (elementUnwrapped.Tag?.Mode == TagModes.Explicit)
        {
            var explicitTag = TagFromIr(elementUnwrapped.Tag, constructed: true);
            sb.AppendLine($"{reader}.{readMethod}({tag}, {(openTypeKeyExpr is null ? "static inner" : openTypeKeyExpr + ", static (inner, key)")} =>");
            sb.AppendLine($"{{");
            sb.AppendLine($"    using (inner.EnterExplicit({explicitTag}))");
            sb.AppendLine($"    {{");
            sb.Append("        return ");
            EmitDecodeExpr(
                sb,
                document,
                module,
                itemOwner,
                itemHint,
                CloneUntagged(elementUnwrapped),
                "inner",
                openTypeKeyExpr: openTypeKeyExpr is null ? null : "key",
                fieldOptions: element.Options,
                emittingModule: emittingModule);
            sb.AppendLine(";");
            sb.Append("    }");
            sb.AppendLine();
            sb.Append('}');
            sb.Append(')');
            return;
        }

        sb.Append($"{reader}.{readMethod}({tag}, {(openTypeKeyExpr is null ? "static inner" : openTypeKeyExpr + ", static (inner, key)")} => ");
        EmitDecodeExpr(
            sb,
            document,
            module,
            itemOwner,
            itemHint,
            element,
            "inner",
            openTypeKeyExpr: openTypeKeyExpr is null ? null : "key",
            fieldOptions: element.Options,
            emittingModule: emittingModule);
        sb.Append(')');
    }

    private string CsType(
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        bool optional,
        JsonObject? fieldOptions = null,
        IrModule? emittingModule = null)
    {
        emittingModule ??= module;
        var useLazy = ShouldEmitLazy(document, module, type, fieldOptions);
        var useRetain = !useLazy && ShouldEmitRetainEncoded(document, module, type, fieldOptions);
        var integerRepresentation = TryResolveIntegerRepresentation(document, module, type);
        var original = type;
        var resolvedModule = module;
        type = UnwrapAliases(document, ref resolvedModule, type);

        if (ContainedType(type) is { } content)
        {
            ContainedNaming(document, resolvedModule, original, owner, hint, out var contentModule, out var contentOwner, out var contentHint);
            var contained = $"Asn1Contained<{CsType(document, contentModule, contentOwner, contentHint, content, false, emittingModule: emittingModule)}>";
            return optional ? contained + "?" : contained;
        }

        if (type is SequenceOfType or SetOfType)
        {
            ResolveOfItemNaming(
                document,
                resolvedModule,
                original,
                owner,
                hint,
                out var itemOwner,
                out var itemHint,
                emittingModule);
            var element = type is SetOfType setOf ? setOf.Element : ((SequenceOfType)type).Element;
            // Resolve nested refs in the alias defining module, but qualify names for the emitting namespace.
            var itemType = CsType(
                document,
                resolvedModule,
                itemOwner,
                itemHint,
                element,
                optional: false,
                element.Options,
                emittingModule);
            var listType = $"{itemType}[]";
            var wrapped = useLazy
                ? $"Asn1Lazy<{listType}>"
                : useRetain
                    ? $"Asn1Value<{listType}>"
                    : listType;
            return optional ? wrapped + "?" : wrapped;
        }

        var primitive = ResolvePrimitive(type);
        if (primitive is not null)
        {
            var mapped = primitive switch
            {
                TypeKinds.Boolean => optional ? "bool?" : "bool",
                TypeKinds.Integer => MapIntegerCsType(
                    integerRepresentation ?? IrOptions.IntegerRepresentations.Der,
                    optional),
                TypeKinds.OctetString => optional ? "ReadOnlyMemory<byte>?" : "ReadOnlyMemory<byte>",
                TypeKinds.Null => optional ? "Asn1Null?" : "Asn1Null",
                TypeKinds.Oid => optional ? "Asn1Oid?" : "Asn1Oid",
                TypeKinds.BitString => optional ? "Asn1BitString?" : "Asn1BitString",
                TypeKinds.String => optional ? "string?" : "string",
                TypeKinds.Time => optional ? "DateTimeOffset?" : "DateTimeOffset",
                TypeKinds.Any => optional ? "Asn1Any?" : "Asn1Any",
                _ => "object"
            };
            return mapped;
        }

        var name = NamedTypeName(document, resolvedModule, owner, hint, type, emittingModule);
        var result = useLazy
            ? $"Asn1Lazy<{name}>"
            : useRetain
                ? $"Asn1Value<{name}>"
                : name;
        return optional ? result + "?" : result;
    }

    /// <summary>
    /// Names nested OF element types after the ASN.1 typedef (PolicyMappings_Item) or, for inline OF,
    /// after the enclosing field (Owner_Field_Item) — matching CollectNested.
    /// </summary>
    private void ResolveOfItemNaming(
        IrDocument document,
        IrModule module,
        TypeExpr original,
        string owner,
        string hint,
        out string itemOwner,
        out string itemHint,
        IrModule? emittingModule = null)
    {
        emittingModule ??= module;
        itemHint = "Item";
        var cursor = original;
        var currentModule = module;
        var visited = new HashSet<string>(StringComparer.Ordinal);
        while (true)
        {
            if (IsSingleAlternativeChoice(cursor))
            {
                cursor = ((ChoiceType)cursor).Components[0].Type;
                continue;
            }

            if (cursor is not RefType reference)
            {
                break;
            }

            var key = (reference.Module ?? currentModule.Name) + "::" + reference.Name;
            if (!visited.Add(key))
            {
                break;
            }

            var found = FindWithModule(document, currentModule, reference);
            if (found is null)
            {
                break;
            }

            var (definingModule, def) = found.Value;
            var inner = def.Type;
            if (inner is SequenceOfType or SetOfType)
            {
                itemOwner = IrOptions.CSharpTypeName(def.Options) ?? SanitizeIdentifier(def.Name);
                if (ModuleNamespace(definingModule) != ModuleNamespace(emittingModule))
                    itemOwner = ModuleNamespace(definingModule) + "." + itemOwner;
                return;
            }

            if (IsNamedBitString(inner) || NeedsNamedType(inner) || IsEnumerated(inner) || IsNamedInteger(inner))
            {
                break;
            }

            cursor = inner;
            currentModule = definingModule;
        }

        itemOwner = owner + "_" + SanitizeIdentifier(hint);
    }

    private static string MapIntegerCsType(string representation, bool optional) => representation switch
    {
        IrOptions.IntegerRepresentations.Int32 => optional ? "int?" : "int",
        IrOptions.IntegerRepresentations.UInt32 => optional ? "uint?" : "uint",
        IrOptions.IntegerRepresentations.Int64 => optional ? "long?" : "long",
        IrOptions.IntegerRepresentations.UInt64 => optional ? "ulong?" : "ulong",
        IrOptions.IntegerRepresentations.BigInt => optional ? "BigInteger?" : "BigInteger",
        IrOptions.IntegerRepresentations.Der => optional ? "Asn1Integer?" : "Asn1Integer",
        _ => throw new NotSupportedException($"Unknown integer representation '{representation}'.")
    };

    private string? TryResolveIntegerRepresentation(IrDocument document, IrModule module, TypeExpr type)
    {
        string? explicitRepresentation = null;
        var visited = new HashSet<string>(StringComparer.Ordinal);
        var cursor = type;

        while (true)
        {
            explicitRepresentation ??= IrOptions.IntegerRepresentation(cursor.Options);

            if (IsSingleAlternativeChoice(cursor))
            {
                cursor = ((ChoiceType)cursor).Components[0].Type;
                continue;
            }

            if (cursor is RefType reference)
            {
                var key = (reference.Module ?? module.Name) + "::" + reference.Name;
                if (!visited.Add(key))
                {
                    throw new NotSupportedException($"Circular type alias '{reference.Name}'.");
                }

                var found = FindWithModule(document, module, reference);
                if (found is null)
                {
                    return null;
                }

                var (definingModule, def) = found.Value;
                explicitRepresentation ??= IrOptions.IntegerRepresentation(def.Options);
                var inner = def.Type;
                if (IsNamedBitString(inner) || NeedsNamedType(inner) || IsEnumerated(inner))
                {
                    return null;
                }

                cursor = inner;
                module = definingModule;
                continue;
            }

            if (cursor is not IntegerType integer)
            {
                return null;
            }

            explicitRepresentation ??= IrOptions.IntegerRepresentation(module.Options);
            if (explicitRepresentation is not null)
            {
                return NormalizeIntegerRepresentation(explicitRepresentation);
            }

            if (integer.NamedValues is { Count: > 0 })
            {
                return InferNamedIntegerRepresentation(integer.NamedValues);
            }

            return InferIntegerRepresentation(integer.Constraint);
        }
    }

    /// <summary>
    /// True when this type usage should be wrapped in <c>Asn1Lazy&lt;T&gt;</c> (SEQUENCE/SET/OF only).
    /// </summary>
    private bool ShouldEmitLazy(
        IrDocument document,
        IrModule module,
        TypeExpr type,
        JsonObject? fieldOptions)
    {
        if (!IsLazyEligible(document, module, type))
        {
            return false;
        }

        return ResolveLazyFlag(document, module, type, fieldOptions);
    }

    /// <summary>
    /// True when this type usage should be wrapped in <c>Asn1Value&lt;T&gt;</c> (SEQUENCE/SET/OF only).
    /// Lazy takes precedence when both flags are set.
    /// </summary>
    private bool ShouldEmitRetainEncoded(
        IrDocument document,
        IrModule module,
        TypeExpr type,
        JsonObject? fieldOptions)
    {
        if (!IsLazyEligible(document, module, type))
        {
            return false;
        }

        if (ShouldEmitLazy(document, module, type, fieldOptions))
        {
            return false;
        }

        return ResolveRetainEncodedFlag(document, module, type, fieldOptions);
    }

    private static bool IsCSharpValueTypeEmit(IrModule module, string typeName, TypeExpr type)
    {
        if (IrOptions.IsCSharpValueType(type.Options))
        {
            return true;
        }

        foreach (var assignment in module.Types)
        {
            var name = IrOptions.CSharpTypeName(assignment.Options) ?? SanitizeIdentifier(assignment.Name);
            if (string.Equals(name, typeName, StringComparison.Ordinal)
                && IrOptions.IsCSharpValueType(assignment.Options))
            {
                return true;
            }
        }

        return false;
    }

    private bool IsLazyEligible(IrDocument document, IrModule module, TypeExpr type)
    {
        var unwrapped = UnwrapAliases(document, module, type);
        if (unwrapped is SequenceType or SetType or SequenceOfType or SetOfType)
        {
            return true;
        }

        if (unwrapped is RefType reference)
        {
            var def = Find(document, module, reference);
            return def?.Type is SequenceType or SetType or SequenceOfType or SetOfType;
        }

        return false;
    }

    private bool ResolveLazyFlag(
        IrDocument document,
        IrModule module,
        TypeExpr type,
        JsonObject? fieldOptions) =>
        ResolvePropagatedOptionFlag(document, module, type, fieldOptions, IrOptions.IsLazy);

    private bool ResolveRetainEncodedFlag(
        IrDocument document,
        IrModule module,
        TypeExpr type,
        JsonObject? fieldOptions) =>
        ResolvePropagatedOptionFlag(document, module, type, fieldOptions, IrOptions.IsRetainEncoded);

    private bool ResolvePropagatedOptionFlag(
        IrDocument document,
        IrModule module,
        TypeExpr type,
        JsonObject? fieldOptions,
        Func<JsonObject?, bool> isSet)
    {
        if (isSet(fieldOptions) || isSet(type.Options))
        {
            return true;
        }

        var visited = new HashSet<string>(StringComparer.Ordinal);
        var cursor = type;
        var currentModule = module;
        while (true)
        {
            if (IsSingleAlternativeChoice(cursor))
            {
                cursor = ((ChoiceType)cursor).Components[0].Type;
                if (isSet(cursor.Options))
                {
                    return true;
                }

                continue;
            }

            if (cursor is not RefType reference)
            {
                break;
            }

            var key = (reference.Module ?? currentModule.Name) + "::" + reference.Name;
            if (!visited.Add(key))
            {
                break;
            }

            var found = FindWithModule(document, currentModule, reference);
            if (found is null)
            {
                break;
            }

            var (definingModule, def) = found.Value;
            if (isSet(def.Options) || isSet(def.Type.Options))
            {
                return true;
            }

            var inner = def.Type;
            if (IsNamedBitString(inner) || NeedsNamedType(inner) || IsEnumerated(inner))
            {
                break;
            }

            cursor = inner;
            currentModule = definingModule;
            if (isSet(cursor.Options))
            {
                return true;
            }
        }

        var unwrapped = UnwrapAliases(document, module, type);
        if (isSet(unwrapped.Options))
        {
            return true;
        }

        return isSet(module.Options);
    }

    private static string InferNamedIntegerRepresentation(IReadOnlyList<IrNamedNumber> namedValues)
    {
        foreach (var named in namedValues)
        {
            if (named.Value < int.MinValue || named.Value > int.MaxValue)
            {
                return IrOptions.IntegerRepresentations.Int64;
            }
        }

        return IrOptions.IntegerRepresentations.Int32;
    }

    private static string NormalizeIntegerRepresentation(string representation)
    {
        return representation switch
        {
            IrOptions.IntegerRepresentations.Int32 => IrOptions.IntegerRepresentations.Int32,
            IrOptions.IntegerRepresentations.UInt32 => IrOptions.IntegerRepresentations.UInt32,
            IrOptions.IntegerRepresentations.Int64 => IrOptions.IntegerRepresentations.Int64,
            IrOptions.IntegerRepresentations.UInt64 => IrOptions.IntegerRepresentations.UInt64,
            IrOptions.IntegerRepresentations.BigInt => IrOptions.IntegerRepresentations.BigInt,
            IrOptions.IntegerRepresentations.Der => IrOptions.IntegerRepresentations.Der,
            _ => throw new NotSupportedException($"Unknown integer representation '{representation}'.")
        };
    }

    private static string InferIntegerRepresentation(IrConstraint? constraint)
    {
        if (constraint?.Value is not { } bound || bound.Max is null)
        {
            return IrOptions.IntegerRepresentations.Der;
        }

        var min = bound.Min;
        var max = bound.Max.Value;

        if (min >= int.MinValue && max <= int.MaxValue)
        {
            return IrOptions.IntegerRepresentations.Int32;
        }

        if (min >= 0 && max <= uint.MaxValue)
        {
            return IrOptions.IntegerRepresentations.UInt32;
        }

        if (min >= long.MinValue && max <= long.MaxValue)
        {
            return IrOptions.IntegerRepresentations.Int64;
        }

        if (min >= 0)
        {
            return IrOptions.IntegerRepresentations.UInt64;
        }

        return IrOptions.IntegerRepresentations.Der;
    }

    private string NamedTypeName(
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        IrModule? emittingModule = null)
    {
        emittingModule ??= module;
        if (type is RefType reference)
        {
            var found = FindWithModule(document, module, reference);
            if (found is not null)
            {
                var (definingModule, def) = ResolveAliasOfTarget(document, found.Value.Module, found.Value.Def);
                var typeName = IrOptions.CSharpTypeName(def.Options) ?? SanitizeIdentifier(def.Name);
                var currentNs = ModuleNamespace(emittingModule);
                var definingNs = ModuleNamespace(definingModule);
                if (!string.Equals(currentNs, definingNs, StringComparison.Ordinal))
                {
                    return definingNs + "." + typeName;
                }

                return typeName;
            }

            return SanitizeIdentifier(reference.Name);
        }

        if (NeedsNamedType(type) || IsEnumerated(type) || IsNamedInteger(type))
        {
            return owner + "_" + SanitizeIdentifier(hint);
        }

        return SanitizeIdentifier(hint);
    }

    private static string ModuleNamespace(IrModule module) =>
        IrOptions.CSharpNamespace(module.Options) ?? SanitizeIdentifier(module.Name);

    private string Initializer(
        IrDocument document,
        IrModule module,
        string owner,
        string hint,
        TypeExpr type,
        bool optional,
        JsonObject? fieldOptions = null)
    {
        if (optional)
        {
            return "";
        }

        if (ShouldEmitLazy(document, module, type, fieldOptions)
            || ShouldEmitRetainEncoded(document, module, type, fieldOptions))
        {
            return "";
        }

        // Asn1Integer defaults to 0 (see Asn1Integer.Zero); no property initializer needed.

        var unwrapped = UnwrapAliases(document, module, type);
        if (unwrapped is SequenceOfType or SetOfType)
        {
            ResolveOfItemNaming(document, module, type, owner, hint, out var itemOwner, out var itemHint);
            var element = unwrapped is SetOfType setOf ? setOf.Element : ((SequenceOfType)unwrapped).Element;
            var itemType = CsType(document, module, itemOwner, itemHint, element, optional: false, element.Options);
            return $" = Array.Empty<{itemType}>();";
        }

        return unwrapped switch
        {
            OidType => "",
            StringType => " = \"\";",
            _ => ""
        };
    }

    private string TagExpr(IrDocument document, IrModule module, TypeExpr type)
    {
        type = UnwrapAliases(document, module, type);
        if (type.Tag is not null)
        {
            var constructed = type.Tag.Mode == TagModes.Explicit || IsConstructed(document, module, type);
            return TagFromIr(type.Tag, constructed);
        }

        return UniversalTag(document, module, type);
    }

    private static string TagFromIr(IrTag tag, bool constructed)
    {
        var cls = tag.Class.ToLowerInvariant() switch
        {
            TagClasses.Universal => "Asn1TagClass.Universal",
            TagClasses.Application => "Asn1TagClass.Application",
            TagClasses.Private => "Asn1TagClass.Private",
            _ => "Asn1TagClass.ContextSpecific"
        };

        return $"new Asn1Tag({cls}, {tag.Number.ToString(CultureInfo.InvariantCulture)}, {(constructed ? "true" : "false")})";
    }

    private string UniversalTag(IrDocument document, IrModule module, TypeExpr type)
    {
        return type switch
        {
            BooleanType => "Asn1Tag.Boolean",
            IntegerType => "Asn1Tag.Integer",
            EnumeratedType => "Asn1Tag.Enumerated",
            BitStringType => "Asn1Tag.BitString",
            OctetStringType => "Asn1Tag.OctetString",
            NullType => "Asn1Tag.Null",
            OidType => "Asn1Tag.ObjectIdentifier",
            StringType stringType => StringFormTag(stringType.Form),
            TimeType timeType => TimeFormTag(timeType.Form),
            SetType or SetOfType => "Asn1Tag.Set",
            SequenceType or SequenceOfType => "Asn1Tag.Sequence",
            RefType reference when Find(document, module, reference)?.Type is { } inner =>
                UniversalTag(document, module, inner),
            _ => "Asn1Tag.Sequence"
        };
    }

    private static string StringFormTag(string form) => form switch
    {
        StringTypes.Utf8 => "Asn1Tag.Utf8String",
        StringTypes.Numeric => "Asn1Tag.NumericString",
        StringTypes.Printable => "Asn1Tag.PrintableString",
        StringTypes.Teletex or StringTypes.T61 => "Asn1Tag.TeletexString",
        StringTypes.Videotex => "Asn1Tag.VideotexString",
        StringTypes.Ia5 => "Asn1Tag.Ia5String",
        StringTypes.Graphic => "Asn1Tag.GraphicString",
        StringTypes.Visible => "Asn1Tag.VisibleString",
        StringTypes.General => "Asn1Tag.GeneralString",
        StringTypes.Universal => "Asn1Tag.UniversalString",
        StringTypes.Bmp => "Asn1Tag.BmpString",
        _ => throw new NotSupportedException($"Unknown stringType '{form}'.")
    };

    private static string TimeFormTag(string form) => form switch
    {
        TimeTypes.Utc => "Asn1Tag.UtcTime",
        TimeTypes.Generalized => "Asn1Tag.GeneralizedTime",
        _ => throw new NotSupportedException($"Unknown timeType '{form}'.")
    };

    private static string StringFormEnum(string form) => form switch
    {
        StringTypes.Utf8 => "Asn1StringForm.Utf8",
        StringTypes.Printable => "Asn1StringForm.Printable",
        StringTypes.Teletex => "Asn1StringForm.Teletex",
        StringTypes.T61 => "Asn1StringForm.T61",
        StringTypes.Ia5 => "Asn1StringForm.Ia5",
        StringTypes.Numeric => "Asn1StringForm.Numeric",
        StringTypes.Visible => "Asn1StringForm.Visible",
        StringTypes.Bmp => "Asn1StringForm.Bmp",
        StringTypes.Universal => "Asn1StringForm.Universal",
        StringTypes.General => "Asn1StringForm.General",
        StringTypes.Graphic => "Asn1StringForm.Graphic",
        StringTypes.Videotex => "Asn1StringForm.Videotex",
        _ => throw new NotSupportedException($"Unknown stringType '{form}'.")
    };

    private static string TimeFormEnum(string form) => form switch
    {
        TimeTypes.Utc => "Asn1TimeForm.Utc",
        TimeTypes.Generalized => "Asn1TimeForm.Generalized",
        _ => throw new NotSupportedException($"Unknown timeType '{form}'.")
    };

    private string? ResolvePrimitive(TypeExpr type) => type switch
    {
        BooleanType => TypeKinds.Boolean,
        IntegerType => TypeKinds.Integer,
        BitStringType => TypeKinds.BitString,
        OctetStringType => TypeKinds.OctetString,
        NullType => TypeKinds.Null,
        OidType => TypeKinds.Oid,
        StringType => TypeKinds.String,
        TimeType => TypeKinds.Time,
        AnyType => TypeKinds.Any,
        _ => null
    };

    /// <summary>
    /// Collapse typedef aliases and single-alternative CHOICE to the underlying type used in generated C#.
    /// Stops at multi-alternative CHOICE / SEQUENCE / SET, named BIT STRING, and ENUMERATED (those keep a type).
    /// Follows <c>options.csharp.aliasOf</c> as an explicit C# alias without rewriting IR RHS.
    /// </summary>
    private TypeExpr UnwrapAliases(IrDocument document, IrModule module, TypeExpr type) =>
        UnwrapAliases(document, ref module, type);

    private TypeExpr UnwrapAliases(IrDocument document, ref IrModule module, TypeExpr type)
    {
        var visited = new HashSet<string>(StringComparer.Ordinal);
        while (true)
        {
            if (type is RefType reference)
            {
                var key = (reference.Module ?? module.Name) + "::" + reference.Name;
                if (!visited.Add(key))
                {
                    throw new NotSupportedException($"Circular type alias '{reference.Name}'.");
                }

                var found = FindWithModule(document, module, reference);
                if (found is null)
                {
                    return type;
                }

                if (IrOptions.CSharpAliasOf(found.Value.Def.Options) is { } aliasOf)
                {
                    var (targetModule, targetDef) = ResolveAliasOfTarget(
                        document, found.Value.Module, found.Value.Def);
                    type = new RefType
                    {
                        Name = targetDef.Name,
                        Module = targetModule.Name,
                        Tag = type.Tag,
                        Options = type.Options
                    };
                    module = targetModule;
                    continue;
                }

                var inner = found.Value.Def.Type;
                if (IsNamedBitString(inner) || NeedsNamedType(inner) || IsEnumerated(inner))
                {
                    return type;
                }

                var next = CloneType(inner);
                if (type.Tag is not null && next.Tag is null)
                {
                    next.Tag = type.Tag;
                }

                next.Options = MergeIntegerRepresentationOptions(
                    next.Options,
                    type.Options,
                    found.Value.Def.Options);

                // Keep defining-module context so nested refs (e.g. Name → AttributeTypeAndValue)
                // do not resolve to a same-named local type in the importing module.
                module = found.Value.Module;
                type = next;
                continue;
            }

            if (IsSingleAlternativeChoice(type))
            {
                var choice = (ChoiceType)type;
                var next = CloneType(choice.Components[0].Type);
                if (type.Tag is not null && next.Tag is null)
                {
                    next.Tag = type.Tag;
                }

                type = next;
                continue;
            }

            return type;
        }
    }

    private static JsonObject? MergeIntegerRepresentationOptions(
        JsonObject? target,
        JsonObject? first,
        JsonObject? second)
    {
        if (IrOptions.IntegerRepresentation(target) is not null)
        {
            return target;
        }

        var representation = IrOptions.IntegerRepresentation(first)
            ?? IrOptions.IntegerRepresentation(second);
        return representation is null
            ? target
            : IrOptions.SetIntegerRepresentation(target, representation);
    }

    private static TypeExpr CloneType(TypeExpr type)
    {
        var clone = CloneUntagged(type);
        clone.Tag = type.Tag;
        return clone;
    }

    private bool IsConstructed(IrDocument document, IrModule module, TypeExpr type) => type switch
    {
        SequenceType or SetType or SequenceOfType or SetOfType or ChoiceType => true,
        RefType reference => Find(document, module, reference)?.Type is { } inner && IsConstructed(document, module, inner),
        _ => false
    };

    private IEnumerable<IrComponent> SortedSetComponents(
        IrDocument document,
        IrModule module,
        IReadOnlyList<IrComponent> components) =>
        components
            .Select((component, index) => (component, index, key: ComponentTagSortKey(document, module, component.Type)))
            .OrderBy(x => x.key.TagClass)
            .ThenBy(x => x.key.Number)
            .ThenBy(x => x.index)
            .Select(x => x.component);

    private (int TagClass, int Number) ComponentTagSortKey(IrDocument document, IrModule module, TypeExpr type)
    {
        type = UnwrapAliases(document, module, type);
        if (type.Tag is not null)
        {
            return (TagClassOrdinal(type.Tag.Class), type.Tag.Number);
        }

        return (0, UniversalTagNumber(document, module, type));
    }

    private static int TagClassOrdinal(string tagClass) => tagClass.ToLowerInvariant() switch
    {
        TagClasses.Universal => 0,
        TagClasses.Application => 1,
        TagClasses.Private => 3,
        _ => 2
    };

    private int UniversalTagNumber(IrDocument document, IrModule module, TypeExpr type) => type switch
    {
        BooleanType => 1,
        IntegerType => 2,
        BitStringType => 3,
        OctetStringType => 4,
        NullType => 5,
        OidType => 6,
        EnumeratedType => 10,
        StringType stringType => StringFormTagNumber(stringType.Form),
        TimeType timeType => timeType.Form == TimeTypes.Utc ? 23 : 24,
        SequenceType or SequenceOfType => 16,
        SetType or SetOfType => 17,
        RefType reference when Find(document, module, reference)?.Type is { } inner =>
            UniversalTagNumber(document, module, inner),
        _ => 16
    };

    private static int StringFormTagNumber(string form) => form switch
    {
        StringTypes.Utf8 => 12,
        StringTypes.Numeric => 18,
        StringTypes.Printable => 19,
        StringTypes.Teletex or StringTypes.T61 => 20,
        StringTypes.Videotex => 21,
        StringTypes.Ia5 => 22,
        StringTypes.Graphic => 25,
        StringTypes.Visible => 26,
        StringTypes.General => 27,
        StringTypes.Universal => 28,
        StringTypes.Bmp => 30,
        _ => throw new NotSupportedException($"Unknown stringType '{form}'.")
    };

    private static IrTypeDef? Find(IrDocument document, IrModule module, RefType reference) =>
        FindWithModule(document, module, reference)?.Def;

    private static (IrModule Module, IrTypeDef Def)? FindWithModule(
        IrDocument document,
        IrModule module,
        RefType reference)
    {
        var modules = string.IsNullOrEmpty(reference.Module)
            ? new[] { module }.Concat(document.Modules)
            : document.Modules.Where(m => m.Name == reference.Module);
        foreach (var candidate in modules)
        {
            var match = candidate.Types.FirstOrDefault(t => t.Name == reference.Name);
            if (match is not null)
            {
                return (candidate, match);
            }
        }

        return null;
    }

    /// <summary>
    /// Follow <c>options.csharp.aliasOf</c> to the emit target typedef (cycle already rejected by IrValidator).
    /// </summary>
    private static (IrModule Module, IrTypeDef Def) ResolveAliasOfTarget(
        IrDocument document,
        IrModule module,
        IrTypeDef definition)
    {
        var visited = new HashSet<string>(StringComparer.Ordinal);
        var currentModule = module;
        var current = definition;
        while (true)
        {
            var key = currentModule.Name + "::" + current.Name;
            if (!visited.Add(key))
            {
                throw new NotSupportedException(
                    $"Circular options.csharp.aliasOf at '{current.Name}'.");
            }

            var aliasOf = IrOptions.CSharpAliasOf(current.Options);
            if (aliasOf is null)
            {
                return (currentModule, current);
            }

            if (string.IsNullOrWhiteSpace(aliasOf))
            {
                throw new NotSupportedException(
                    $"Type '{currentModule.Name}.{current.Name}' has empty options.csharp.aliasOf.");
            }

            var found = FindWithModule(document, currentModule, new RefType { Name = aliasOf });
            if (found is null)
            {
                throw new NotSupportedException(
                    $"Type '{currentModule.Name}.{current.Name}' options.csharp.aliasOf '{aliasOf}' does not resolve.");
            }

            currentModule = found.Value.Module;
            current = found.Value.Def;
        }
    }

    private static TypeExpr CloneUntagged(TypeExpr type)
    {
        var clone = type switch
        {
            BooleanType => (TypeExpr)new BooleanType(),
            NullType => new NullType(),
            OctetStringType octets => new OctetStringType { Containing = octets.Containing },
            OidType => new OidType(),
            IntegerType integer => new IntegerType { NamedValues = integer.NamedValues },
            EnumeratedType enumerated => new EnumeratedType { Values = enumerated.Values, Extensible = enumerated.Extensible },
            BitStringType bitString => new BitStringType { NamedBits = bitString.NamedBits, Containing = bitString.Containing },
            StringType stringType => new StringType { Form = stringType.Form },
            TimeType timeType => new TimeType { Form = timeType.Form, FractionDigits = timeType.FractionDigits },
            AnyType any => new AnyType { DefinedBy = any.DefinedBy, Bindings = any.Bindings, Selector = any.Selector, TableExtensible = any.TableExtensible },
            SequenceType sequence => new SequenceType { Components = sequence.Components, Extensible = sequence.Extensible },
            SetType set => new SetType { Components = set.Components, Extensible = set.Extensible },
            ChoiceType choice => new ChoiceType { Components = choice.Components, Extensible = choice.Extensible },
            SequenceOfType sequenceOf => new SequenceOfType { Element = sequenceOf.Element },
            SetOfType setOf => new SetOfType { Element = setOf.Element },
            RefType reference => new RefType { Name = reference.Name, Module = reference.Module },
            _ => throw new NotSupportedException($"Cannot clone untagged type kind '{type.Kind}'.")
        };
        clone.Options = type.Options;
        clone.Constraint = type.Constraint;
        return clone;
    }

    private static string WriteCall(
        string writer,
        string tag,
        string expr,
        TypeExpr type) => type switch
    {
        BooleanType => $"{writer}.WriteBoolean({tag}, {expr})",
        IntegerType => $"{writer}.WriteInteger({tag}, {expr})",
        BitStringType => $"{writer}.WriteBitString({tag}, {expr})",
        OctetStringType => $"{writer}.WriteOctetString({tag}, {expr}.Span)",
        NullType => $"{writer}.WriteNull({tag})",
        OidType => $"{writer}.WriteObjectIdentifier({tag}, {expr})",
        StringType stringType => $"{writer}.WriteString({tag}, {expr}, {StringFormEnum(stringType.Form)})",
        TimeType timeType => timeType.Form == TimeTypes.Generalized
            ? $"{writer}.WriteTime({tag}, {expr}, {TimeFormEnum(timeType.Form)}, {timeType.FractionDigits ?? 3})"
            : $"{writer}.WriteTime({tag}, {expr}, {TimeFormEnum(timeType.Form)})",
        _ => throw new InvalidOperationException(type.Kind)
    };

    private static string ReadCall(
        string reader,
        string tag,
        TypeExpr type,
        string? integerRepresentation) => type switch
    {
        BooleanType => $"{reader}.ReadBoolean({tag})",
        IntegerType => IntegerReadCall(reader, tag, integerRepresentation),
        BitStringType => $"{reader}.ReadBitString({tag})",
        OctetStringType => $"{reader}.ReadOctetString({tag})",
        NullType => $"Asn1Null.Decode({reader}, {tag})",
        OidType => $"{reader}.ReadOid({tag})",
        StringType stringType => $"{reader}.ReadString({tag}, {StringFormEnum(stringType.Form)})",
        TimeType timeType => $"{reader}.ReadTime({tag}, {TimeFormEnum(timeType.Form)})",
        _ => throw new InvalidOperationException(type.Kind)
    };

    private static string IntegerReadCall(string reader, string tag, string? representation) =>
        (representation ?? IrOptions.IntegerRepresentations.Der) switch
        {
            IrOptions.IntegerRepresentations.Int32 => $"{reader}.ReadInt32({tag})",
            IrOptions.IntegerRepresentations.UInt32 => $"{reader}.ReadUInt32({tag})",
            IrOptions.IntegerRepresentations.Int64 => $"{reader}.ReadInt64({tag})",
            IrOptions.IntegerRepresentations.UInt64 => $"{reader}.ReadUInt64({tag})",
            IrOptions.IntegerRepresentations.BigInt => $"{reader}.ReadInteger({tag})",
            IrOptions.IntegerRepresentations.Der => $"{reader}.ReadIntegerValue({tag})",
            _ => throw new NotSupportedException($"Unknown integer representation '{representation}'.")
        };

    private static string PropertyName(IrComponent field, string? enclosingTypeName = null)
    {
        var name = IrOptions.CSharpPropertyName(field.Options) ?? SanitizeIdentifier(field.Name);
        if (Keywords.Contains(name))
        {
            name = "@" + name;
        }

        if (enclosingTypeName is not null &&
            string.Equals(name, enclosingTypeName.Split('.').Last(), StringComparison.Ordinal))
        {
            name += "Value";
        }

        return name;
    }

    private static string CamelCaseIdentifier(string identifier)
    {
        var name = identifier.StartsWith('@') ? identifier[1..] : identifier;
        if (name.Length == 0)
        {
            return "value";
        }

        var camel = char.ToLowerInvariant(name[0]) + name[1..];
        return Keywords.Contains(camel) ? "@" + camel : camel;
    }

    internal static string SanitizeIdentifier(string name)
    {
        var parts = name.Split(new[] { '-', '_' }, StringSplitOptions.RemoveEmptyEntries);
        var result = string.Concat(parts.Select(p => char.ToUpperInvariant(p[0]) + (p.Length > 1 ? p[1..] : "")));
        return string.IsNullOrEmpty(result) ? "Type" : result;
    }
